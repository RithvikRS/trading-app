import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import axe from 'axe-core'
import App from './App'
import { formatMoney, money } from './data/money'
import { readRoute } from './routes'

async function open() {
  window.history.replaceState(null, '', '/#/budgets')
  const mounted = render(<App />), user = userEvent.setup()
  await user.click(screen.getByRole('button', { name: 'Cash flow' }))
  await user.click(screen.getByRole('button', { name: 'Show 28 source records' }))
  return { ...mounted, user }
}
const summary = () => screen.getByRole('region', { name: 'Cash-flow summary' })
const sources = () => document.querySelector('.cash-sources') as HTMLElement
const reconciliation = () => screen.getByRole('region', { name: 'From classified activity to bank movement' })
async function correct(user: ReturnType<typeof userEvent.setup>, value: string) {
  const panel = within(screen.getByRole('dialog'))
  await user.selectOptions(panel.getByLabelText('New category'), value)
  await user.click(panel.getByRole('button', { name: 'Preview correction' }))
  await user.click(panel.getByRole('button', { name: 'Apply 1 change' }))
}

describe('cash-flow workspace', () => {
  it('starts with October MTD and exact totals, while keeping budget scope independent', async () => {
    const { user } = await open()
    expect(summary().textContent).toContain('₹95,250'); expect(summary().textContent).toContain('₹35,964.9'); expect(summary().textContent).toContain('₹59,285.1')
    expect(reconciliation().textContent).toContain('₹45,785.1')
    expect(document.querySelector('.cash-comparison')?.textContent).toContain('Same 20 calendar days')
    expect(document.querySelector('.cash-comparison')?.textContent).toContain('need classification')
    expect(screen.getByRole('button', { name: 'Recurring' }).getAttribute('aria-pressed')).toBe('false')
    await user.selectOptions(screen.getByLabelText('Cash-flow account'), 'sbi')
    expect(summary().textContent).toContain('₹250')
    await user.click(screen.getByRole('button', { name: 'Monthly budgets' }))
    expect(screen.getByRole('region', { name: 'Monthly budget summary' }).textContent).toContain('₹38,199')
    expect(document.body.textContent).toContain('HDFC & SBI')
  })
  it('selects months and days by keyboard, distinguishes negative refunds, zero days and future gaps, and keeps month summaries stable', async () => {
    const { user } = await open()
    const september = screen.getByRole('button', { name: /^Inspect September 2026/ })
    september.focus(); await user.keyboard('{Enter}')
    expect((screen.getByLabelText('Cash-flow month') as HTMLSelectElement).value).toBe('2026-09')
    const original = summary().textContent
    expect(document.querySelector('.cash-comparison')?.textContent).toContain('Same 30 calendar days')
    const refundDay = screen.getByRole('button', { name: /^Inspect 5 Sept 2026/ })
    fireEvent.keyDown(refundDay, { key: 'Enter' })
    expect(sources().textContent).toContain('Refund of August purchase'); expect(summary().textContent).toBe(original)
    await user.click(screen.getByRole('button', { name: 'Show daily table' }))
    const daily = document.getElementById('cash-daily-table')!
    expect(within(daily).getByRole('button', { name: '5 Sept 2026' }).closest('tr')?.textContent).toContain('-₹1,500')
    await user.click(within(daily).getByRole('button', { name: '4 Sept 2026' }))
    expect(sources().textContent).toContain('Posted movement is zero')
    await user.selectOptions(screen.getByLabelText('Cash-flow month'), '2026-10')
    await user.click(within(daily).getByRole('button', { name: '21 Oct 2026' }))
    expect(sources().textContent).toContain('Missing coverage does not mean zero')
    expect(within(daily).getByRole('button', { name: '21 Oct 2026' }).closest('tr')?.textContent).toContain('Not supplied')
    await user.click(screen.getByRole('button', { name: 'Show whole month' }))
    expect(within(sources()).getAllByRole('link')).toHaveLength(28)
  })
  it('shares category changes with budgets, bank inspection and undo without altering bank movement', async () => {
    const { user } = await open()
    await user.selectOptions(screen.getByLabelText('Source category'), 'unresolved')
    await user.click(within(sources()).getByRole('link', { name: /Unresolved payment/ }))
    await correct(user, 'shopping')
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Close transaction details' }))
    expect(document.activeElement?.id).toBe('cash-sources-title')
    expect(summary().textContent).toContain('₹39,464.9'); expect(reconciliation().textContent).toContain('₹45,785.1')
    await user.click(screen.getByRole('button', { name: 'Monthly budgets' }))
    expect(screen.getByRole('region', { name: 'Monthly budget summary' }).textContent).toContain('₹39,459')
    await user.click(screen.getByRole('link', { name: 'Banking' }))
    expect(screen.getAllByRole('link', { name: /^Inspect / })).toHaveLength(28)
    await user.click(screen.getByRole('button', { name: 'Undo last change' }))
    await user.click(screen.getByRole('link', { name: 'Budgets' })); await user.click(screen.getByRole('button', { name: 'Cash flow' }))
    expect(summary().textContent).toContain('₹35,964.9')
  })
  it('corrects a historical purchase, previews its linked refund, and filters the refund under its new category', async () => {
    const { user } = await open()
    await user.selectOptions(screen.getByLabelText('Cash-flow month'), '2026-08')
    await user.click(within(sources()).getByRole('link', { name: /August home purchase/ }))
    const panel = within(screen.getByRole('dialog'))
    await user.selectOptions(panel.getByLabelText('New category'), 'health'); await user.click(panel.getByRole('button', { name: 'Preview correction' }))
    expect(screen.getByRole('dialog').textContent).toContain('Linked refund: Refund of August purchase')
    await user.click(panel.getByRole('button', { name: 'Apply 1 change' })); await user.click(panel.getByRole('button', { name: 'Close transaction details' }))
    expect(document.activeElement?.id).toBe('cash-link-t33')
    await user.selectOptions(screen.getByLabelText('Cash-flow month'), '2026-09'); await user.selectOptions(screen.getByLabelText('Source category'), 'health')
    expect(sources().textContent).toContain('Refund of August purchase'); expect(within(sources()).getAllByRole('link')).toHaveLength(2)
    await user.selectOptions(screen.getByLabelText('Source category'), 'refund')
    expect(within(sources()).getAllByRole('link')).toHaveLength(1)
  })
  it('restores source focus on Back/Forward, retains filters across navigation, and supports historical direct reload', async () => {
    const { user, unmount } = await open()
    await user.selectOptions(screen.getByLabelText('Cash-flow month'), '2026-09'); await user.selectOptions(screen.getByLabelText('Cash-flow account'), 'hdfc')
    await user.click(within(sources()).getByRole('link', { name: /Refund of August purchase/ }))
    await act(async () => window.history.back()); await waitFor(() => expect(window.location.hash).toBe('#/budgets'))
    expect(document.activeElement?.id).toBe('cash-link-t51')
    await act(async () => window.history.forward()); await waitFor(() => expect(screen.getByRole('dialog').textContent).toContain('Refund of August purchase'))
    fireEvent(screen.getByRole('dialog'), new Event('cancel', { cancelable: true }))
    await user.click(screen.getByRole('link', { name: 'Overview' })); await user.click(screen.getByRole('link', { name: 'Budgets' }))
    expect((screen.getByLabelText('Cash-flow month') as HTMLSelectElement).value).toBe('2026-09')
    expect((screen.getByLabelText('Cash-flow account') as HTMLSelectElement).value).toBe('hdfc')
    unmount(); window.history.replaceState(null, '', '/#/banking/t33'); render(<App />)
    expect(readRoute('#/banking/t33').screen).toBe('transaction'); expect(readRoute('#/banking/t99').screen).toBe('unavailable')
    expect(screen.getByRole('dialog').textContent).toContain('1 Aug 2026–31 Aug 2026')
    expect(screen.getByRole('dialog').textContent).toContain('sample-hdfc-aug')
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Close transaction details' }))
    expect(window.location.hash).toBe('#/banking')
    fireEvent.change(screen.getByLabelText('From booking date'), { target: { value: '2026-08-01' } })
    fireEvent.change(screen.getByLabelText('To booking date'), { target: { value: '2026-08-31' } })
    expect(screen.getAllByRole('link', { name: /^Inspect / })).toHaveLength(15)
    expect(screen.getByRole('region', { name: 'Bank balance snapshots' }).textContent).toContain('₹1,86,420')
  })
  it('converts summaries, chart axes, monthly/daily tables, bridge, sources, comparisons, and statements', async () => {
    const { user } = await open()
    await user.click(screen.getByRole('button', { name: 'Show daily table' }))
    await user.click(screen.getByText('Statement balances, coverage & pending records'))
    for (const currency of ['USD', 'INR'] as const) {
      await user.selectOptions(screen.getByLabelText('Display currency'), currency)
      expect(summary().textContent).toContain(formatMoney(money('95250'), currency))
      expect(document.querySelector('.cash-month-axis')?.textContent).toContain(formatMoney(money('95250'), currency))
      expect(document.querySelector('.cash-trends table')?.textContent).toContain(formatMoney(money('37204.90'), currency))
      expect(document.getElementById('cash-daily-table')?.textContent).toContain(formatMoney(money('-800'), currency))
      expect(reconciliation().textContent).toContain(formatMoney(money('45785.10'), currency))
      expect(sources().textContent).toContain(formatMoney(money('95000'), currency))
      expect(document.querySelector('.cash-statements')?.textContent).toContain(formatMoney(money('186420'), currency))
      expect(document.querySelector('.cash-workspace')?.textContent).not.toContain(currency === 'USD' ? '₹' : '$')
    }
    await user.selectOptions(screen.getByLabelText('Cash-flow month'), '2026-09'); await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    expect(document.querySelector('.cash-comparison')?.textContent).toContain(formatMoney(money('5010'), 'USD'))
  })
  it('removes masked values, ratios, chart geometry and attributes without storing financial state', async () => {
    const { user, container } = await open()
    await user.selectOptions(screen.getByLabelText('Cash-flow month'), '2026-09')
    await user.click(screen.getByRole('button', { name: 'Show daily table' })); await user.click(screen.getByText('Statement balances, coverage & pending records'))
    await user.click(screen.getByRole('button', { name: 'Hide amounts' }))
    expect(container.textContent).not.toMatch(/[₹$%]|95,240|58,035|1,500/)
    expect(container.querySelector('.cash-chart')).toBeNull(); expect(container.querySelector('.cash-month-chart')).toBeNull()
    for (const element of container.querySelectorAll('*')) for (const attribute of element.attributes) expect(attribute.value).not.toMatch(/[₹$%]|95240|58035|1500/)
    for (const status of screen.getAllByRole('status')) expect(status.textContent).not.toMatch(/[₹$%]/)
    expect(JSON.stringify(localStorage)).not.toMatch(/cash|2026-09|95240|category/); expect(sessionStorage.length).toBe(0)
    expect(window.location.hash).toBe('#/budgets')
    await user.click(screen.getByRole('button', { name: 'Show amounts' })); expect(summary().textContent).toContain('₹95,240')
  })
  it('retains controls in partial/error/retry/loading, resets them on empty, and resets reviews on reload', async () => {
    const { user, unmount } = await open()
    await user.selectOptions(screen.getByLabelText('Cash-flow account'), 'sbi'); await user.click(screen.getByRole('button', { name: 'Show daily table' }))
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(document.querySelector('.cash-coverage')?.textContent).toContain('Source coverage incomplete')
    expect(within(document.getElementById('cash-daily-table')!).getByRole('button', { name: '20 Oct 2026' }).closest('tr')?.textContent).toContain('Not supplied')
    await user.click(screen.getByText('Statement balances, coverage & pending records'))
    expect(document.querySelector('.cash-statements')?.textContent).toContain('-₹2,200')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error'); const previous = summary().textContent
    await user.click(screen.getByRole('button', { name: 'Retry demo' })); await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    expect(summary().textContent).toBe(previous)
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading'); expect(screen.queryByRole('region', { name: 'Cash-flow summary' })).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'populated'); expect((screen.getByLabelText('Cash-flow account') as HTMLSelectElement).value).toBe('sbi')
    expect(screen.getByRole('button', { name: 'Hide daily table' })).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty'); expect(screen.queryByLabelText('Cash-flow account')).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial'); expect((screen.getByLabelText('Cash-flow account') as HTMLSelectElement).value).toBe('')
    expect(screen.getByRole('button', { name: 'Show daily table' })).toBeTruthy()
    unmount(); const fresh = render(<App />)
    expect(screen.getByRole('region', { name: 'Monthly budget summary' })).toBeTruthy(); fresh.unmount()
  })
  it.each(['workspace', 'daily table', 'masked'])('has no structural accessibility violations in %s', async mode => {
    const { user, container } = await open()
    if (mode === 'daily table') await user.click(screen.getByRole('button', { name: 'Show daily table' }))
    if (mode === 'masked') await user.click(screen.getByRole('button', { name: 'Hide amounts' }))
    const result = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(result.violations.map(item => item.id)).toEqual([])
  })
})
