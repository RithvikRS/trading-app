import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import axe from 'axe-core'
import App from './App'
import TransferReview from './TransferReview'
import { getBankTransactions } from './data/banking'
import { changeTransfers, createTransferState, initialTransferControls, pairId } from './data/transfers'

function open() { window.history.replaceState(null, '', '/#/banking'); return render(<App />) }
function review() { return screen.getByRole('region', { name: 'Transfer review' }) }
function status(name: string) { return within(screen.getByRole('group', { name: 'Transfer review status' })).getByRole('button', { name: new RegExp(`^${name}`) }) }
async function enter(user: ReturnType<typeof userEvent.setup>) { await user.click(screen.getByRole('button', { name: /^Transfers/ })) }
async function confirm(user: ReturnType<typeof userEvent.setup>) { await user.click(screen.getByRole('button', { name: 'Review pair' })); await user.click(screen.getByRole('button', { name: 'Confirm this pair' })) }

describe('transfer review workspace', () => {
  it('explains all review states and requires selection before confirming a unique pair', async () => {
    const user = userEvent.setup(); open(); await enter(user)
    expect(status('Suggested').textContent).toBe('Suggested1')
    expect(status('Ambiguous').textContent).toBe('Ambiguous2')
    expect(status('Unmatched').textContent).toBe('Unmatched1')
    expect(status('Confirmed').textContent).toBe('Confirmed1')
    expect(review().textContent).toContain('Matching structured source reference')
    expect(review().textContent).toContain('Sample transfer A')
    expect(screen.queryByRole('button', { name: 'Confirm this pair' })).toBeNull()
    await confirm(user)
    expect(status('Confirmed').textContent).toBe('Confirmed2')
    expect(review().textContent).toContain('₹33,000')
    expect(review().textContent).toContain('₹8,500')
    expect(document.activeElement?.id).toBe('transfer-review-title')
    await user.click(screen.getByRole('button', { name: 'Activity' }))
    await user.click(screen.getByRole('link', { name: /^Inspect Account movement at HDFC Bank, 10 Oct/ }))
    const panel = screen.getByRole('dialog')
    expect(panel.textContent).toContain('Recorded categoryUncategorized')
    expect(panel.textContent).toContain('Effective categoryInternal transfer')
    expect(panel.textContent).toContain('Transfer confirmed')
  })
  it('shows all competing pairs and supports pair-specific dismissal, restore and undo', async () => {
    const user = userEvent.setup(); open(); await enter(user); await user.click(status('Ambiguous'))
    const cards = within(review()).getAllByRole('article')
    expect(cards).toHaveLength(2)
    await user.click(within(cards[0]!).getByRole('button', { name: 'Dismiss candidate' }))
    expect(status('Dismissed').textContent).toBe('Dismissed1')
    expect(status('Suggested').textContent).toBe('Suggested2')
    await user.click(status('Dismissed'))
    await user.click(screen.getByRole('button', { name: 'Restore candidate' }))
    expect(status('Ambiguous').textContent).toBe('Ambiguous2')
    await user.click(screen.getByRole('button', { name: 'Undo last change' }))
    expect(status('Dismissed').textContent).toBe('Dismissed1')
    await user.click(screen.getByRole('button', { name: 'Undo last change' }))
    expect(status('Ambiguous').textContent).toBe('Ambiguous2')
    expect((screen.getByRole('button', { name: 'Undo last change' }) as HTMLButtonElement).disabled).toBe(true)
    await user.click(status('Ambiguous'))
    await user.click(within(within(review()).getAllByRole('article')[1]!).getByRole('button', { name: 'Review pair' }))
    await user.click(screen.getByRole('button', { name: 'Confirm this pair' }))
    expect(status('Ambiguous').textContent).toBe('Ambiguous0')
    expect(status('Unmatched').textContent).toBe('Unmatched2')
  })
  it('inspects a counterpart outside filters and restores the exact review link, controls and history navigation', async () => {
    const user = userEvent.setup(); open()
    await user.selectOptions(screen.getByLabelText('Bank account'), 'hdfc')
    await enter(user)
    expect(review().textContent).toContain('Outside activity filters')
    const link = within(review()).getByRole('link', { name: 'Inspect credit at SBI, 11 Oct 2026' })
    await user.click(link)
    expect(window.location.hash).toBe('#/banking/t20')
    await user.click(screen.getByRole('button', { name: 'Close transaction details' }))
    expect(document.activeElement?.id).toBe('transfer-link-pair-t10-t20-t20')
    expect(status('Suggested').getAttribute('aria-pressed')).toBe('true')
    await act(async () => { window.history.back() })
    await waitFor(() => expect(screen.getByRole('dialog', { name: 'Account movement received' })).toBeTruthy())
    await act(async () => { window.history.forward() })
    await waitFor(() => expect(document.activeElement?.id).toBe('transfer-link-pair-t10-t20-t20'))
    await user.click(screen.getByRole('button', { name: 'Activity' }))
    expect((screen.getByLabelText('Bank account') as HTMLSelectElement).value).toBe('hdfc')
  })
  it('updates the Overview excerpt when the initial pair is unlinked and restores both legs on undo', async () => {
    const user = userEvent.setup(); open(); await enter(user); await user.click(status('Confirmed'))
    await user.click(screen.getByRole('button', { name: 'Unlink pair' }))
    expect(status('Confirmed').textContent).toBe('Confirmed0')
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    expect(screen.getByRole('region', { name: 'Recent activity' }).textContent).toContain('Account movement needs review')
    await user.click(screen.getByRole('link', { name: 'Banking' }))
    expect(status('Confirmed').getAttribute('aria-pressed')).toBe('true')
    await user.click(screen.getByRole('button', { name: 'Undo last change' }))
    expect(status('Confirmed').textContent).toBe('Confirmed1')
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    expect(screen.getByRole('region', { name: 'Recent activity' }).textContent).toContain('Confirmed pair')
  })
  it('preserves compatible decisions through partial/loading/error states and clears them on empty/reset/reload', async () => {
    const user = userEvent.setup(); const view = open(); await enter(user); await confirm(user)
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(status('Confirmed').textContent).toBe('Confirmed2')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error')
    expect(status('Confirmed').textContent).toBe('Confirmed2')
    await user.click(screen.getByRole('button', { name: 'Retry demo' }))
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading')
    expect(screen.queryByRole('button', { name: 'Confirm this pair' })).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'populated')
    expect(status('Confirmed').textContent).toBe('Confirmed2')
    await user.click(screen.getByRole('button', { name: 'Reset sample decisions' }))
    expect(status('Confirmed').textContent).toBe('Confirmed1')
    expect((screen.getByRole('button', { name: 'Undo last change' }) as HTMLButtonElement).disabled).toBe(true)
    await confirm(user)
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    expect(screen.queryByRole('region', { name: 'Transfer review' })).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Explore sample banking' }))
    expect(status('Confirmed').textContent).toBe('Confirmed1')
    await confirm(user)
    expect(JSON.stringify(localStorage)).not.toMatch(/t10|t20|pair-|transfer|8000/)
    expect(sessionStorage.length).toBe(0)
    view.unmount(); open(); await enter(user)
    expect(status('Confirmed').textContent).toBe('Confirmed1')
  })
  it('converts every pair/coverage amount and masks all original values, references, attributes and announcements', async () => {
    const user = userEvent.setup(); const { container } = open(); await enter(user)
    await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    expect(review().textContent).toContain('$95.81')
    expect(review().textContent).toContain('Original INR · ₹8,000')
    await user.click(screen.getByRole('button', { name: 'Hide amounts' }))
    expect(container.textContent).not.toMatch(/[₹$]|Sample transfer A|Sample reference 10/)
    expect(container.querySelector('.amount')).toBeNull()
    await confirm(user)
    for (const element of container.querySelectorAll('*')) for (const attribute of element.attributes) expect(attribute.value).not.toMatch(/[₹$]|8000/)
    for (const message of screen.getAllByRole('status')) expect(message.textContent).not.toMatch(/[₹$]|8000/)
    await user.click(status('Confirmed'))
    await user.click(within(within(review()).getAllByRole('article')[1]!).getByRole('link', { name: 'Inspect debit at HDFC Bank, 10 Oct 2026' }))
    expect(screen.getByRole('dialog').textContent).toContain('Narration hidden')
    expect(container.textContent).not.toMatch(/[₹$]|INR 8000/)
  })
  it('explains missing-leg coverage without offering to confirm an incomplete pair', () => {
    const records = getBankTransactions()
    const state = changeTransfers(createTransferState(), { type: 'confirm', pair: { id: pairId('t10', 't20'), debitId: 't10', creditId: 't20' } }, records)
    render(<TransferReview records={records.filter(item => item.id !== 't20')} state={state} controls={{ ...initialTransferControls, view: 'transfers' }} visibleIds={new Set()} onControls={() => {}} onAction={() => {}} onOpen={() => {}} />)
    expect(screen.getByRole('alert').textContent).toContain('Both sides are treated as unresolved')
    expect(screen.getByRole('button', { name: 'Unlink incomplete pair' })).toBeTruthy()
    expect(screen.queryByRole('button', { name: 'Confirm this pair' })).toBeNull()
  })
  it.each([false, true])('has no detectable structural accessibility violations with selected=%s', async selected => {
    const user = userEvent.setup(); const { container } = open(); await enter(user)
    if (selected) await user.click(screen.getByRole('button', { name: 'Review pair' }))
    expect(screen.getByRole('button', { name: selected ? 'Cancel review' : 'Review pair' }).getAttribute('aria-expanded')).toBe(String(selected))
    const results = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(results.violations.map(item => item.id)).toEqual([])
    if (selected) fireEvent.click(screen.getByRole('button', { name: 'Cancel review' }))
    expect(screen.queryByRole('button', { name: 'Confirm this pair' })).toBeNull()
  })
})
