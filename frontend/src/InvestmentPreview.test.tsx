import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import axe from 'axe-core'
import { describe, expect, it, vi } from 'vitest'
import App from './App'
import { readRoute } from './routes'
const open = (id = 'i08') => { window.history.replaceState(null, '', `/#/connections/imports/${id}`); return { ...render(<App />), user: userEvent.setup() } }
const button = (name: string | RegExp) => screen.getByRole('button', { name })
const click = (name: string | RegExp) => fireEvent.click(button(name))
const suggestions = () => { click(/^Review suggested choices/); click('Confirm review change') }
const state = (value: string) => fireEvent.change(screen.getByLabelText('Demo state'), { target: { value } })
const navigate = (hash: string) => act(() => { window.history.replaceState(null, '', `/${hash}`); window.dispatchEvent(new PopStateEvent('popstate')) })

describe('Investment import walkthroughs', () => {
  it('adds investment catalog/source entry and restores source/filter focus', async () => {
    const { user } = open(); navigate('#/connections'); click('Sources')
    await user.click(button(/^UBS/)); await user.click(screen.getByRole('link', { name: 'Inspect investment sample' }))
    expect(window.location.hash).toBe('#/connections/imports/i12')
    await user.click(screen.getByRole('link', { name: 'Back to sources' })); await waitFor(() => expect(document.activeElement?.id).toBe('source-import-ubs'))
    click('Sample imports'); fireEvent.change(screen.getByRole('combobox', { name: 'Sample type' }), { target: { value: 'investment' } })
    expect(screen.getByText('7 of 14 samples')).toBeTruthy()
    await user.click(screen.getByRole('link', { name: 'One folio, two sources' })); await user.click(screen.getByRole('link', { name: 'Back to sample imports' }))
    await waitFor(() => expect(document.activeElement?.id).toBe('import-link-i10'))
    expect((screen.getByRole('combobox', { name: 'Sample type' }) as HTMLSelectElement).value).toBe('investment')
    for (const id of ['i08', 'i14']) expect(readRoute(`#/connections/imports/${id}`).screen).toBe('import')
    for (const id of ['i15', 'i08/position-h01', 'i10?folio=1', '../i10']) expect(readRoute(`#/connections/imports/${id}`).screen).toBe('unavailable')
  })
  it('completes a snapshot with cash counted once and shows its limited scope', () => {
    open(); click(/^Review suggested choices/); click('Cancel review change')
    expect(screen.queryByText(/Import review history/)).toBeNull()
    suggestions(); expect(screen.getByText('4 new source identities selected')).toBeTruthy()
    expect(screen.getByRole('region', { name: 'Selected native evidence groups' }).textContent).toContain('₹18,500')
    click('Complete sample review'); expect(screen.getByRole('region', { name: 'Investment review change preview' }).textContent).toContain('Complete transactions, lots, tax basis, and full account coverage are not supplied')
    click('Cancel review change'); click('Complete sample review'); click('Confirm sample completion')
    expect(screen.getByRole('heading', { name: 'Sample review completed.' })).toBeTruthy()
    expect(screen.getByText('Review receipt · i08 / r1')).toBeTruthy()
    click('Reopen sample review'); click('Confirm review change'); expect(screen.queryByText(/Review receipt/)).toBeNull()
    click('Undo review change'); expect(screen.getByText('Review receipt · i08 / r1')).toBeTruthy()
  })
  it('inspects a fund source preference, cancels/restores choices, and never adds another position', async () => {
    const { user } = open('i10'); click('Inspect position-h11')
    const inspector = within(screen.getByRole('dialog'))
    await user.click(inspector.getByText('Inspect evidence · cas-folio-b'))
    expect(inspector.getByText('consolidated-example')).toBeTruthy()
    click('Use incoming snapshot'); click('Cancel row choice'); expect(inspector.getByText('Needs decision')).toBeTruthy()
    click('Keep comparison snapshot'); click('Confirm row choice')
    expect(inspector.getByRole('status').textContent).toBe('Keep comparison snapshot')
    click('Restore row decision'); click('Confirm row choice'); expect(inspector.getByRole('status').textContent).toBe('Needs decision')
    click('Use incoming snapshot'); click('Confirm row choice')
    await user.click(button('Close import row')); await waitFor(() => expect(document.activeElement?.id).toBe('import-row-position-h11'))
    expect(screen.getByText('0 new source identities selected')).toBeTruthy()
    expect(screen.getByRole('region', { name: 'Selected native evidence groups' }).textContent).toContain('₹3,10,000')
    expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
  })
  it('separates regular/direct plans and permits a position-only review with valuation unknown', () => {
    open('i11'); suggestions(); click('Inspect position-h13')
    const inspector = within(screen.getByRole('dialog'))
    expect(inspector.getByText(/Quote unavailable. Position identity may be reviewed/)).toBeTruthy()
    expect(inspector.getByText(/Northstar Nifty 50 Index Fund · Advisor funds · Regular/)).toBeTruthy()
    click('Close import row'); expect(screen.getByText('1 unavailable · Known subtotal only')).toBeTruthy()
    expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
  })
  it('shows matching UBS lots with missing basis/history, and keeps exclusions blocked', () => {
    open('i12'); suggestions(); click('Inspect lot-b')
    const inspector = within(screen.getByRole('dialog'))
    expect(inspector.getByText(/Fee or tax basis is unavailable/)).toBeTruthy()
    expect(inspector.getByText('6.5')).toBeTruthy()
    click('Exclude from this sample review'); click('Confirm row choice'); click('Close import row')
    expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
    click('Undo review change'); click('Set sample aside'); click('Confirm review change')
    expect(screen.getByRole('heading', { name: 'This sample is set aside.' })).toBeTruthy()
    click('Reopen sample review'); click('Confirm review change'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(screen.getByRole('combobox', { name: 'Record kind' }), { target: { value: 'cash' } })
    expect(screen.getByText('1 of 5 records shown')).toBeTruthy(); click('Inspect cash-dividend')
    expect(within(screen.getByRole('region', { name: 'Normalized investment fields' })).getByText('Withholding')).toBeTruthy()
  })
  it('keeps filters independent from source checks and navigates canonical copies with contained focus', async () => {
    const { user } = open(); fireEvent.change(screen.getByRole('combobox', { name: 'Row disposition' }), { target: { value: 'duplicate' } })
    const totals = screen.getByRole('region', { name: 'Selected native evidence groups' }).textContent
    click('Inspect cash-ind-in-copy'); click('Inspect canonical row cash-ind-in')
    const inspector = within(screen.getByRole('dialog'))
    await user.click(button('Include candidate')); await user.click(button('Cancel row choice'))
    await waitFor(() => expect(document.activeElement).toBe(inspector.getByRole('button', { name: 'Include candidate' })))
    await user.click(button('Exclude from this sample review')); await user.click(button('Cancel row choice'))
    await waitFor(() => expect(document.activeElement).toBe(inspector.getByRole('button', { name: 'Exclude from this sample review' })))
    await user.tab()
    expect(document.activeElement).toBe(inspector.getByRole('button', { name: 'Hide amounts in import inspector' }))
    fireEvent(screen.getByRole('dialog'), new Event('cancel', { cancelable: true })); await waitFor(() => expect(document.activeElement?.id).toBe('import-rows-title'))
    expect(screen.getByText('1 of 5 records shown')).toBeTruthy(); expect(screen.getByRole('region', { name: 'Selected native evidence groups' }).textContent).toBe(totals)
  })
  it('shares bank/investment undo and reset but leaves financial totals and connection state intact', () => {
    open(); suggestions(); navigate('#/connections/imports/i01'); suggestions(); click('Complete sample review'); click('Confirm sample completion')
    navigate('#/connections/imports/i08'); click('Undo review change')
    navigate('#/connections/imports/i01'); expect(screen.queryByRole('heading', { name: 'Sample review completed.' })).toBeNull()
    navigate('#/connections'); click('Sources'); click('Reset sample connection states')
    navigate('#/connections/imports/i08'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
    click('Reset sample import reviews'); click('Confirm import reset')
    navigate('#/connections/imports/i01'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
    navigate('#/overview'); expect(within(screen.getByRole('region', { name: 'Asset summary' })).getByText('₹50,86,080')).toBeTruthy()
  })
  it('converts every primary amount while units remain exact; masking removes financial and hostile text', () => {
    const fetchSpy = vi.spyOn(globalThis, 'fetch')
    try {
      const { container } = open('i14'); suggestions()
      fireEvent.change(screen.getByLabelText('Display currency'), { target: { value: 'USD' } })
      click('Complete sample review')
      for (const amount of container.querySelectorAll('.reporting-amount > .amount')) expect(amount.textContent).toContain('$')
      click('Hide amounts'); expect(screen.queryByRole('region', { name: 'Investment review change preview' })).toBeNull()
      expect(container.innerHTML).not.toMatch(/[₹$]|1,120|1,240|1120\.00/)
      expect(container.querySelector('.investment-units')).toBeNull(); expect(screen.queryByRole('searchbox')).toBeNull()
      click('Show amounts'); click('Complete sample review'); click('Confirm sample completion'); click('Hide amounts')
      expect(screen.queryByText(/Review receipt/)).toBeNull()
      navigate('#/connections/imports/i13'); click('Show amounts'); click('Inspect unsupported-event')
      expect(within(screen.getByRole('dialog')).getByRole('heading', { name: '<img src=x onerror=alert(1)>' })).toBeTruthy()
      expect(container.querySelector('img,script,input[type=file],input[type=password]')).toBeNull()
      click('Exclude from this sample review'); click('Hide amounts in import inspector')
      expect(screen.queryByRole('region', { name: 'Confirm investment choice' })).toBeNull()
      expect(container.innerHTML).not.toMatch(/[₹$]|alert\(1\)|onerror|FICTIONAL \/|1120\.00/)
      expect((button('Exclude from this sample review') as HTMLButtonElement).disabled).toBe(true)
      expect(fetchSpy).not.toHaveBeenCalled(); expect(localStorage.length).toBe(1)
      expect(Object.keys(JSON.parse(localStorage.getItem(localStorage.key(0)!)!)).sort()).toEqual(['currency', 'hidden', 'theme'])
    } finally { fetchSpy.mockRestore() }
  })
  it('retains compatible drafts through history/partial/error, and clears pending work on loading/empty/reload', () => {
    const { unmount } = open(); suggestions(); fireEvent.change(screen.getByRole('combobox', { name: 'Record kind' }), { target: { value: 'cash' } }); click('Inspect cash-ind-in')
    navigate('#/connections/imports/i09'); expect(screen.queryByRole('dialog')).toBeNull(); navigate('#/connections/imports/i08')
    expect(document.activeElement?.id).toBe('import-row-title'); click('Close import row')
    state('partial'); state('error'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
    click('Complete sample review'); state('loading'); expect(screen.queryByRole('region', { name: 'Investment review change preview' })).toBeNull()
    state('populated'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false); expect(screen.getByText('2 of 5 records shown')).toBeTruthy()
    state('empty'); click('Explore sample imports'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
    suggestions(); unmount(); render(<App />); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
  })
  it('has no detected structural accessibility violations in source preferences, masked inspection, and completion', async () => {
    const { container } = open('i10'); click('Inspect position-h11'); click('Use incoming snapshot')
    expect((await axe.run(screen.getByRole('dialog'), { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
    click('Hide amounts in import inspector')
    expect((await axe.run(screen.getByRole('dialog'), { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
    click('Show amounts in import inspector'); click('Use incoming snapshot'); click('Confirm row choice'); click('Close import row'); click('Complete sample review')
    expect((await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
  })
})
