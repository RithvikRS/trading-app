import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import axe from 'axe-core'
import App from './App'
import { readScreen } from './routes'

function renderInvestments() {
  window.history.replaceState(null, '', '/#/investments')
  return render(<App />)
}
function table() { return screen.getByRole('table', { name: /Investment holdings/ }) }
function summary() { return screen.getByRole('region', { name: 'Investment summary' }) }

describe('Investments', () => {
  it('renders account-specific holding links and reconciles the summary', () => {
    renderInvestments()
    expect(within(summary()).getByText('₹47,96,290')).toBeTruthy()
    expect(within(table()).getAllByRole('row')).toHaveLength(15)
    expect(within(table()).getAllByRole('row', { name: /Accenture/ })).toHaveLength(2)
    expect(within(table()).getAllByRole('link')).toHaveLength(14)
    expect(within(table()).getByRole('link', { name: 'View Accenture at UBS' }).getAttribute('href')).toBe('#/investments/h14')
    expect(screen.getByRole('status').textContent).toBe('Showing 14 of 14 holdings')
  })
  it('combines search and filters, clears no matches, and retains the full portfolio denominator', async () => {
    const user = userEvent.setup()
    renderInvestments()
    await user.type(screen.getByRole('searchbox'), ' acn ')
    await user.selectOptions(screen.getByLabelText('Account'), 'ubs')
    expect(screen.getByRole('status').textContent).toContain('Showing 1 of 14')
    expect(within(table()).getByText('12.5%')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Filters' }))
    await user.selectOptions(screen.getByLabelText('Native currency'), 'INR')
    expect(screen.getByRole('status').textContent).toContain('Showing 0 of 14')
    expect(screen.getByText('No holdings match these filters.')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Clear all' }))
    expect(within(table()).getAllByRole('row')).toHaveLength(15)
  })
  it('sorts through column controls and converts quotes with labeled originals when reporting currency changes', async () => {
    const user = userEvent.setup()
    renderInvestments()
    await user.click(screen.getByRole('button', { name: 'Sort by value (inr)' }))
    expect(within(table()).getAllByRole('row')[1]?.textContent).toContain('Accenture')
    expect(screen.getByRole('button', { name: 'Sort by value (inr)' }).closest('th')?.getAttribute('aria-sort')).toBe('ascending')
    await user.type(screen.getByRole('searchbox'), 'USTM')
    expect(within(table()).getByText('$600.00')).toBeTruthy()
    expect(within(table()).getByText('₹50,100.00')).toBeTruthy()
    expect(within(table()).getByText('₹4,13,325')).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    expect(within(table()).getByText('$600.00')).toBeTruthy()
    expect(within(table()).getByText('$4,950.00')).toBeTruthy()
    expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('USTM')
  })
  it('masks quantities, quotes and monetary values in DOM and accessible attributes across screens', async () => {
    const user = userEvent.setup()
    const { container } = renderInvestments()
    expect(container.querySelector('.holding-number')).not.toBeNull()
    await user.click(screen.getByRole('button', { name: 'Hide amounts' }))
    expect(container.textContent).not.toMatch(/[₹$]/)
    expect(container.querySelector('.holding-number')).toBeNull()
    for (const node of container.querySelectorAll('[aria-label], [aria-valuetext], [title]')) {
      expect(['aria-label', 'aria-valuetext', 'title'].map(name => node.getAttribute(name)).join(' ')).not.toMatch(/[₹$]/)
    }
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    await waitFor(() => expect(screen.getByRole('heading', { level: 1 }).textContent).toContain('Everything'))
    expect(container.textContent).not.toMatch(/[₹$]/)
    await user.click(screen.getByRole('link', { name: 'Investments' }))
    await waitFor(() => expect(screen.getByRole('heading', { level: 1 }).textContent).toContain('Every holding'))
    expect(container.textContent).not.toMatch(/[₹$]/)
  })
  it('retains partial valuations on failure and never substitutes zero for an unpriced selection', async () => {
    const user = userEvent.setup()
    renderInvestments()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(within(summary()).getByText('₹43,71,290')).toBeTruthy()
    expect(within(table()).getByText('NAV missing')).toBeTruthy()
    expect(within(table()).getByText('Holdings stale')).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Account'), 'advisor')
    expect(screen.getByText('Matching known value').parentElement?.textContent).not.toContain('₹0')
    expect(within(table()).getByLabelText('Value unavailable')).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error')
    expect(screen.getByRole('alert').textContent).toContain('last available')
    expect(within(summary()).getByText('₹43,71,290')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Retry demo' }))
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    expect(within(table()).getByText('NAV missing')).toBeTruthy()
  })
  it('distinguishes loading and empty from filtered no-results, and resets sample holdings', async () => {
    const user = userEvent.setup()
    renderInvestments()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading')
    expect(screen.getByRole('status').textContent).toBe('Loading sample holdings')
    expect(screen.queryByRole('table')).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    expect(screen.getByRole('heading', { name: 'No investment holdings yet.' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Explore sample holdings' }))
    expect(within(table()).getAllByRole('row')).toHaveLength(15)
  })
  it('keeps controls in memory across navigation and handles unsafe-looking text as plain text', async () => {
    const user = userEvent.setup()
    const { container, unmount } = renderInvestments()
    const query = '<img src=x onerror=alert(1)>'
    await user.type(screen.getByRole('searchbox'), query)
    expect(container.querySelector('img')).toBeNull()
    expect(window.location.hash).toBe('#/investments')
    expect(JSON.stringify(localStorage)).not.toContain(query)
    expect(sessionStorage.length).toBe(0)
    await user.clear(screen.getByRole('searchbox'))
    await user.type(screen.getByRole('searchbox'), 'northstar')
    await user.selectOptions(screen.getByLabelText('Sort'), 'name:asc')
    Object.defineProperty(window, 'scrollY', { configurable: true, value: 240 })
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    await waitFor(() => expect(screen.queryByRole('searchbox')).toBeNull())
    Object.defineProperty(window, 'scrollY', { configurable: true, value: 0 })
    await act(async () => { window.history.back() })
    await waitFor(() => expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('northstar'))
    expect((screen.getByLabelText('Sort') as HTMLSelectElement).value).toBe('name:asc')
    expect(document.activeElement?.id).toBe('page-title')
    await waitFor(() => expect(window.scrollTo).toHaveBeenLastCalledWith({ top: 240, behavior: 'instant' }))
    unmount()
    renderInvestments()
    expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('')
  })
  it('keeps focus on the destination after the navigation drawer finishes closing', async () => {
    const user = userEvent.setup()
    renderInvestments()
    // Browsers queue the close event; it may arrive after the route has changed.
    const close = vi.spyOn(HTMLDialogElement.prototype, 'close').mockImplementation(function (this: HTMLDialogElement) { this.removeAttribute('open') })
    try {
      await user.click(screen.getByRole('button', { name: 'Open navigation' }))
      const drawer = screen.getByRole('dialog', { name: 'Navigation' })
      await user.click(within(drawer).getByRole('link', { name: 'Overview' }))
      await waitFor(() => expect(screen.getByRole('heading', { level: 1 }).textContent).toContain('Everything'))
      fireEvent(drawer, new Event('close'))
      expect(document.activeElement?.id).toBe('page-title')
      await user.click(screen.getByRole('button', { name: 'Open navigation' }))
      await user.click(within(drawer).getByRole('button', { name: 'Close navigation' }))
      fireEvent(drawer, new Event('close'))
      expect(document.activeElement?.getAttribute('aria-label')).toBe('Open navigation')
    } finally { close.mockRestore() }
  })
  it('allowlists routes and provides a safe unavailable screen', () => {
    expect(readScreen('#/investments')).toBe('investments')
    expect(readScreen('#/overview')).toBe('overview')
    expect(readScreen('#/investments/h14')).toBe('holding')
    expect(readScreen('#/investments/h99')).toBe('unavailable')
    window.history.replaceState(null, '', '/#/unknown')
    render(<App />)
    expect(screen.getByRole('heading', { name: 'This view is unavailable.' })).toBeTruthy()
    expect(screen.getByRole('link', { name: 'Go to investments' })).toBeTruthy()
  })
  it('has named controls and table headers without detectable structural accessibility violations', async () => {
    const { container } = renderInvestments()
    const result = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(result.violations.map(item => `${item.id}: ${item.description}`)).toEqual([])
  })
})
