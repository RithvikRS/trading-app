import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import axe from 'axe-core'
import { describe, expect, it, vi } from 'vitest'
import App from './App'
import { readRoute } from './routes'

function open(id = 'i01') { window.history.replaceState(null, '', id ? `/#/connections/imports/${id}` : '/#/connections'); return { ...render(<App />), user: userEvent.setup() } }
const dialog = () => within(screen.getByRole('dialog'))
const changeState = (value: string) => fireEvent.change(screen.getByLabelText('Demo state'), { target: { value } })
const history = (hash: string) => act(() => { window.history.replaceState(null, '', `/${hash}`); window.dispatchEvent(new PopStateEvent('popstate')) })

describe('Bank import catalog, previews and row inspection', () => {
  it('allowlists batch routes and never interprets row data as navigation', () => {
    expect(readRoute('#/connections/imports/i01')).toEqual({ screen: 'import', importId: 'i01' })
    for (const path of ['i99', 'i01/row-t01', '../i01', 'i01?amount=1', '<script>', '__proto__']) expect(readRoute(`#/connections/imports/${path}`)).toEqual({ screen: 'unavailable' })
    open('i99'); expect(screen.queryByRole('heading', { name: 'Statement evidence' })).toBeNull()
  })
  it('filters the catalog, opens a preview, and restores its filter, focus and scroll origin', async () => {
    const { user } = open('')
    await user.click(screen.getByRole('button', { name: 'Sample imports' }))
    expect(screen.getByText('7 of 7 samples')).toBeTruthy()
    await user.selectOptions(screen.getByRole('combobox', { name: 'Sample bank' }), 'sbi')
    await user.type(screen.getByRole('searchbox', { name: 'Search import samples' }), 'conflicting')
    expect(screen.getByText('1 of 7 samples')).toBeTruthy()
    await user.click(screen.getByRole('link', { name: 'A conflicting source record' }))
    expect(window.location.hash).toBe('#/connections/imports/i05')
    expect(screen.getByRole('heading', { name: 'The statement has an unexplained difference.' })).toBeTruthy()
    await user.click(screen.getByRole('link', { name: 'Back to sample imports' }))
    await waitFor(() => expect(document.activeElement?.id).toBe('import-link-i05'))
    expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('conflicting')
    expect((screen.getByRole('combobox', { name: 'Sample bank' }) as HTMLSelectElement).value).toBe('sbi')
  })
  it('enters bank samples from source details and returns to the expanded source', async () => {
    const { user } = open('')
    await user.click(screen.getByRole('button', { name: /^HDFC Bank/ }))
    await user.click(screen.getByRole('link', { name: 'Inspect bank sample' }))
    expect(window.location.hash).toBe('#/connections/imports/i01')
    await user.click(screen.getByRole('link', { name: 'Back to sources' }))
    await waitFor(() => expect(document.activeElement?.id).toBe('source-import-hdfc'))
    expect(screen.getByRole('region', { name: 'HDFC Bank source details' })).toBeTruthy()
  })
  it('filters incoming rows without changing whole-batch counts, amounts or arithmetic', async () => {
    const { user } = open('i03')
    const counts = screen.getByRole('region', { name: 'Whole-batch row counts' }).textContent
    const totals = screen.getByRole('region', { name: 'Whole-batch amounts' }).textContent
    await user.selectOptions(screen.getByRole('combobox', { name: 'Row disposition' }), 'overlap')
    expect(screen.getByText('1 of 16 rows shown')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Inspect row-t06' }))
    expect(dialog().getByText(/Similarity does not prove a duplicate/)).toBeTruthy()
    await user.click(dialog().getByText('Inspect evidence · row-t05'))
    expect(dialog().getAllByText('source-t05').length).toBe(1)
    fireEvent(screen.getByRole('dialog'), new Event('cancel', { cancelable: true }))
    await waitFor(() => expect(document.activeElement?.id).toBe('import-row-row-t06'))
    expect(screen.getByRole('region', { name: 'Whole-batch row counts' }).textContent).toBe(counts)
    expect(screen.getByRole('region', { name: 'Whole-batch amounts' }).textContent).toBe(totals)
    await user.selectOptions(screen.getByRole('combobox', { name: 'Incoming account' }), 'sbi')
    expect(screen.getByText('No rows match.')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Clear row filters' }))
    expect(screen.getByText('16 of 16 rows shown')).toBeTruthy()
  })
  it('inspects a canonical row outside the active filter and returns focus to the rows heading', async () => {
    const { user } = open('i04')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Row disposition' }), 'duplicate')
    await user.click(screen.getByRole('button', { name: 'Inspect row-t05-copy' }))
    await user.click(dialog().getByRole('button', { name: 'Inspect canonical row row-t05' }))
    expect(dialog().getByText('New candidate')).toBeTruthy()
    const close = dialog().getByRole('button', { name: 'Close import row' })
    close.focus(); await user.tab()
    expect(document.activeElement).toBe(dialog().getByRole('button', { name: 'Hide amounts in import inspector' }))
    await user.tab({ shift: true }); expect(document.activeElement).toBe(close)
    await user.click(close)
    await waitFor(() => expect(document.activeElement?.id).toBe('import-rows-title'))
    expect(screen.getByText('1 of 3 rows shown')).toBeTruthy()
  })
  it('preserves per-batch filters and selection across history, then clears them on reload', async () => {
    const { user, unmount } = open('i05')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Row disposition' }), 'conflict')
    await user.click(screen.getByRole('button', { name: 'Inspect row-t26' }))
    history('#/connections/imports/i04')
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(screen.getByText('3 of 3 rows shown')).toBeTruthy()
    history('#/connections/imports/i05')
    expect(document.activeElement?.id).toBe('import-row-title')
    expect(dialog().getByText('Conflict')).toBeTruthy()
    unmount(); render(<App />)
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(screen.getByText('12 of 12 rows shown')).toBeTruthy()
  })
  it('shows invalid source text as text and missing monetary values as unavailable', async () => {
    const { user, container } = open('i06')
    await user.click(screen.getByRole('button', { name: 'Inspect issue-amount' }))
    expect(within(dialog().getByRole('region', { name: 'Normalized incoming fields' })).getByLabelText('Value unavailable')).toBeTruthy()
    expect(dialog().getByText('22,000')).toBeTruthy()
    await user.click(dialog().getByRole('button', { name: 'Close import row' }))
    await user.click(screen.getByRole('button', { name: 'Inspect issue-kind' }))
    expect(dialog().getByRole('heading', { name: '<img src=x onerror=alert(1)>' })).toBeTruthy()
    expect(dialog().getByText('FICTIONAL RAW TEXT / <script>alert(1)</script> / INR 3200.00')).toBeTruthy()
    expect(container.querySelector('img, script, input[type="file"], input[type="password"], form')).toBeNull()
    expect(screen.queryByRole('button', { name: /Complete sample|Include candidate|Save|Skip as duplicate/ })).toBeNull()
  })
  it('converts every primary preview amount to USD, preserving labeled native evidence and conflict versions', async () => {
    const { user, container } = open('i05')
    await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    for (const value of container.querySelectorAll('.reporting-amount > .amount')) expect(value.textContent).toContain('$')
    expect(container.querySelectorAll('.original-value').length).toBeGreaterThan(10)
    await user.click(screen.getByRole('button', { name: 'Inspect row-t26' }))
    await user.click(dialog().getByText('Inspect evidence · row-t26'))
    const normalized = within(dialog().getByRole('region', { name: 'Normalized incoming fields' }))
    expect(normalized.getByText('$27.54')).toBeTruthy()
    expect(dialog().getByText('$26.35')).toBeTruthy()
    expect(dialog().getByText('2300.00')).toBeTruthy(); expect(dialog().getByText('2200.00')).toBeTruthy()
  })
  it('removes raw source text, searches and monetary DOM/attributes when masked, without requests or persistence', async () => {
    const fetchSpy = vi.spyOn(globalThis, 'fetch')
    try {
      const { user, container } = open('i06')
      await user.type(screen.getByRole('searchbox', { name: 'Search incoming rows' }), '<img')
      await user.click(screen.getByRole('button', { name: 'Inspect issue-kind' }))
      await user.click(dialog().getByRole('button', { name: 'Hide amounts in import inspector' }))
      expect(container.innerHTML).not.toMatch(/[₹$]|95000|95,000|3200|3,200|onerror|alert\(1\)|FICTIONAL RAW TEXT|&lt;img/)
      expect(screen.queryByRole('searchbox')).toBeNull()
      expect(dialog().getByRole('heading', { name: 'Source description hidden' })).toBeTruthy()
      await user.click(dialog().getByRole('button', { name: 'Close import row' }))
      await user.click(screen.getByRole('button', { name: 'Use dark theme' }))
      await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
      expect(localStorage.length).toBe(1)
      expect(JSON.parse(localStorage.getItem(localStorage.key(0)!)!)).toEqual({ theme: 'dark', currency: 'USD', hidden: true })
      expect(window.location.hash).toBe('#/connections/imports/i06')
      await user.click(screen.getByRole('button', { name: 'Show amounts' }))
      expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('')
      expect(fetchSpy).not.toHaveBeenCalled()
    } finally { fetchSpy.mockRestore() }
  })
  it('retains fixed evidence through partial/error, closes inspection for loading, and resets controls for empty', async () => {
    const { user } = open('i03')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Row disposition' }), 'overlap')
    await user.click(screen.getByRole('button', { name: 'Inspect row-t06' }))
    changeState('loading')
    expect(screen.queryByRole('dialog')).toBeNull(); expect(screen.getByRole('status').textContent).toBe('Loading sample imports')
    expect(screen.queryByRole('region', { name: 'Whole-batch amounts' })).toBeNull()
    changeState('partial')
    expect(screen.getByText(/Portfolio coverage is partial; this example retains its own supplied evidence/)).toBeTruthy()
    expect(screen.getByText('1 of 16 rows shown')).toBeTruthy()
    changeState('error'); expect(screen.getByRole('alert')).toBeTruthy()
    expect(screen.getByText('1 of 16 rows shown')).toBeTruthy()
    changeState('empty'); expect(screen.getByText('No import samples loaded.')).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Explore sample imports' }))
    expect(screen.getByText('16 of 16 rows shown')).toBeTruthy()
  })
  it('keeps connection resets separate from import controls and financial totals', async () => {
    const { user } = open('i05')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Row disposition' }), 'conflict')
    await user.click(screen.getByRole('link', { name: 'Back to sample imports' }))
    await user.click(screen.getByRole('button', { name: 'Sources' }))
    await user.click(screen.getByRole('button', { name: 'Reset sample connection states' }))
    await user.click(screen.getByRole('button', { name: 'Sample imports' }))
    await user.click(screen.getByRole('link', { name: 'A conflicting source record' }))
    expect(screen.getByText('1 of 12 rows shown')).toBeTruthy()
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    expect(within(screen.getByRole('region', { name: 'Asset summary' })).getByText('₹50,86,080')).toBeTruthy()
  })
  it('has no detected structural accessibility violations in preview, matching evidence, and masked dark inspection', async () => {
    const { user, container } = open('i05')
    expect((await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
    await user.click(screen.getByRole('button', { name: 'Use dark theme' }))
    await user.click(screen.getByRole('button', { name: 'Inspect row-t26' }))
    await user.click(dialog().getByText('Inspect evidence · row-t26'))
    expect((await axe.run(screen.getByRole('dialog'), { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
    await user.click(dialog().getByRole('button', { name: 'Hide amounts in import inspector' }))
    expect((await axe.run(screen.getByRole('dialog'), { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
  })
})
