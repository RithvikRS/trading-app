import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import axe from 'axe-core'
import App from './App'
import { readRoute } from './routes'
import { budgetOverview, createBudgetState } from './data/budgets'
import { bankCategories, getBankTransactions } from './data/banking'
import { createTransferState } from './data/transfers'
import { formatMoney } from './data/money'

function open(hash = '#/budgets') { window.history.replaceState(null, '', `/${hash}`); return render(<App />) }
const summary = () => screen.getByRole('region', { name: 'Monthly budget summary' })
const editor = () => within(screen.getByRole('dialog', { name: / budget$/ }))
const detail = (name: string) => screen.getByRole('region', { name: `${name} spending details` })
async function setLimit(user: ReturnType<typeof userEvent.setup>, name: string, value: string) {
  await user.click(screen.getByRole('button', { name: `${name} budget` }))
  await user.clear(editor().getByLabelText('Monthly limit · INR')); await user.type(editor().getByLabelText('Monthly limit · INR'), value)
  await user.click(editor().getByRole('button', { name: 'Save limit' }))
}

describe('monthly budget workspace', () => {
  it('enables navigation and direct routes, shows full limits against available month-to-date actuals', () => {
    open()
    expect(readRoute('#/budgets')).toEqual({ screen: 'budgets' })
    expect(readRoute('#/budgets/2026-09').screen).toBe('unavailable')
    expect(screen.getByRole('link', { name: 'Budgets' }).getAttribute('aria-current')).toBe('page')
    expect(summary().textContent).toContain('₹38,199'); expect(summary().textContent).toContain('₹35,959'); expect(summary().textContent).toContain('₹2,240')
    expect(document.body.textContent).toContain('Both statements cover 1–20 October')
    expect(screen.getByRole('button', { name: 'Cash flow' })).toBeTruthy()
    expect(screen.queryByRole('button', { name: 'Recurring' })).toBeNull()
  })
  it('validates editing without coercion, cancels unchanged, saves zero, removes, undoes and resets', async () => {
    const user = userEvent.setup(); open()
    const original = summary().textContent
    await user.click(screen.getByRole('button', { name: 'Edit Food & groceries budget' }))
    await user.clear(editor().getByLabelText('Monthly limit · INR'))
    await user.type(editor().getByLabelText('Monthly limit · INR'), '1,200')
    await user.click(editor().getByRole('button', { name: 'Save limit' }))
    expect(editor().getByRole('alert').textContent).toContain('Do not use commas')
    expect(summary().textContent).toBe(original)
    await user.click(editor().getByRole('button', { name: 'Cancel' }))
    expect(document.activeElement?.id).toBe('budget-edit-groceries')
    expect((screen.getByRole('button', { name: 'Undo budget change' }) as HTMLButtonElement).disabled).toBe(true)
    await setLimit(user, 'Edit Food & groceries', '0')
    expect(summary().textContent).toContain('₹32,199')
    await user.click(screen.getByRole('button', { name: 'Edit Food & groceries budget' }))
    await user.click(editor().getByRole('button', { name: 'Remove category limit' }))
    expect(screen.getByRole('button', { name: 'Set Food & groceries budget' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Undo budget change' }))
    expect(screen.getByRole('button', { name: 'Edit Food & groceries budget' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Undo budget change' }))
    expect(summary().textContent).toBe(original)
    await setLimit(user, 'Set Bank fees', '10.25')
    expect(summary().textContent).toContain('₹38,209.25')
    await user.click(screen.getByRole('button', { name: 'Reset sample budgets' }))
    expect(summary().textContent).toBe(original)
  })
  it('uses current classifications, updates refunds, and separates budget reset from Banking undo/reset', async () => {
    const user = userEvent.setup(); open()
    await setLimit(user, 'Edit Health', '2000')
    await user.click(screen.getByRole('button', { name: 'Shopping' }))
    expect(detail('Shopping').textContent).toContain('₹800')
    await user.click(within(detail('Shopping')).getByRole('link', { name: /Home essentials/ }))
    let panel = within(screen.getByRole('dialog'))
    await user.selectOptions(panel.getByLabelText('New category'), 'health')
    await user.click(panel.getByRole('button', { name: 'Preview correction' })); await user.click(panel.getByRole('button', { name: 'Apply 1 change' }))
    await user.click(panel.getByRole('button', { name: 'Close transaction details' }))
    expect(window.location.hash).toBe('#/budgets')
    expect(document.activeElement?.id).toBe('budget-categories-title')
    expect(detail('Shopping').textContent).toContain('No classified records')
    await user.click(screen.getByRole('button', { name: 'Health' }))
    expect(detail('Health').textContent).toContain('₹4,000')
    await user.click(screen.getByRole('button', { name: 'Reset sample budgets' }))
    await user.click(screen.getByRole('button', { name: 'Health' }))
    expect(detail('Health').textContent).toContain('₹4,000')
    await setLimit(user, 'Edit Health', '2000')
    await user.click(screen.getByRole('link', { name: 'Review categories' }))
    expect(screen.getByRole('heading', { name: 'Category review' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Reset sample decisions' }))
    await user.click(screen.getByRole('link', { name: 'Budgets' }))
    expect(detail('Health').textContent).toContain('₹1,600')
    expect(summary().textContent).toContain('₹40,199')
  })
  it('restores source-link focus and supports Back/Forward and direct inspector reload', async () => {
    const user = userEvent.setup(); const mounted = open()
    await user.click(screen.getByRole('button', { name: 'Shopping' }))
    await user.click(within(detail('Shopping')).getByRole('link', { name: /Partial purchase refund/ }))
    await act(async () => window.history.back())
    await waitFor(() => expect(window.location.hash).toBe('#/budgets'))
    expect(document.activeElement?.id).toBe('budget-link-t08')
    await act(async () => window.history.forward())
    await waitFor(() => expect(screen.getByRole('dialog').textContent).toContain('Partial purchase refund'))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Close transaction details' }))
    expect(document.activeElement?.id).toBe('budget-link-t08')
    mounted.unmount(); open('#/banking/t08')
    expect(screen.getByRole('link', { name: 'Banking' }).getAttribute('aria-current')).toBe('page')
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Close transaction details' }))
    expect(window.location.hash).toBe('#/banking')
  })
  it('converts every budget amount and detail while keeping edit amounts in canonical INR', async () => {
    const user = userEvent.setup(); open()
    const totals = budgetOverview(createBudgetState(), getBankTransactions(), createTransferState(), false)
    for (const currency of ['USD', 'INR'] as const) {
      await user.selectOptions(screen.getByLabelText('Display currency'), currency)
      for (const row of totals.rows) {
        const el = screen.getByRole('button', { name: bankCategories[row.category] }).closest('li')!
        expect(el.textContent).toContain(formatMoney(row.net, currency))
        if (row.limit) expect(el.textContent).toContain(formatMoney(row.limit, currency))
      }
      expect(summary().textContent).toContain(formatMoney(totals.remaining, currency))
    }
    await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    await user.click(screen.getByRole('button', { name: 'Shopping' }))
    expect(detail('Shopping').textContent).toContain('$28.74'); expect(detail('Shopping').textContent).toContain('Original INR')
    await user.click(screen.getByRole('button', { name: 'Edit Shopping budget' }))
    expect((editor().getByLabelText('Monthly limit · INR') as HTMLInputElement).value).toBe('3000.00')
    expect(screen.getByRole('dialog').textContent).toContain('$35.93')
  })
  it('masks input drafts, values and financial geometry without persisting planning data', async () => {
    const user = userEvent.setup(); const { container } = open()
    await user.click(screen.getByRole('button', { name: 'Shopping' }))
    await user.click(screen.getByRole('button', { name: 'Edit Shopping budget' }))
    await user.clear(editor().getByLabelText('Monthly limit · INR')); await user.type(editor().getByLabelText('Monthly limit · INR'), '51234.56')
    await user.click(editor().getByRole('button', { name: 'Hide amounts in budget editor' }))
    expect(editor().queryByRole('textbox')).toBeNull()
    expect((editor().getByRole('button', { name: 'Save limit' }) as HTMLButtonElement).disabled).toBe(true)
    expect(container.textContent).not.toMatch(/[₹$]|51234|38,199|35,959/)
    expect(container.querySelector('.budget-progress')).toBeNull()
    for (const el of container.querySelectorAll('*')) for (const attribute of el.attributes) expect(attribute.value).not.toMatch(/[₹$]|51234|38199|35959/)
    expect(JSON.stringify(localStorage)).not.toMatch(/budget|51234|shopping/); expect(sessionStorage.length).toBe(0)
    expect(window.location.hash).toBe('#/budgets')
    await user.click(editor().getByRole('button', { name: 'Show amounts in budget editor' }))
    expect((editor().getByLabelText('Monthly limit · INR') as HTMLInputElement).value).toBe('51234.56')
    await user.click(editor().getByRole('button', { name: 'Save limit' }))
    expect(screen.getByRole('status').textContent).not.toMatch(/[₹$]|51234/)
  })
  it('retains limits through navigation and partial/error/retry, hides loading and resets on empty/reload', async () => {
    const user = userEvent.setup(); const mounted = open()
    await setLimit(user, 'Edit Food & groceries', '8000')
    await user.click(screen.getByRole('link', { name: 'Overview' })); await user.click(screen.getByRole('link', { name: 'Budgets' }))
    expect(summary().textContent).toContain('₹40,199')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(summary().textContent).toContain('₹33,759')
    expect(screen.getByRole('heading', { name: 'Source coverage is incomplete.' })).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error')
    expect(summary().textContent).toContain('₹40,199')
    await user.click(screen.getByRole('button', { name: 'Retry demo' })); await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading')
    expect(screen.queryByRole('region', { name: 'Monthly budget summary' })).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'populated')
    expect(summary().textContent).toContain('₹40,199')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    expect(screen.queryByRole('region', { name: 'Monthly budget summary' })).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    await user.click(screen.getByText('Coverage & calculation details'))
    expect(screen.getByRole('heading', { name: 'Source coverage is incomplete.' }).closest('section')?.textContent).toContain('₹16,500')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    await user.click(screen.getByRole('button', { name: 'Explore sample budgets' }))
    expect(summary().textContent).toContain('₹38,199')
    await setLimit(user, 'Edit Health', '3000')
    mounted.unmount(); open(); expect(summary().textContent).toContain('₹38,199')
  })
  it('contains editor focus and returns on Escape, including the mobile navigation destination', async () => {
    const user = userEvent.setup(); open('#/overview')
    await user.click(screen.getByRole('button', { name: 'Open navigation' }))
    await user.click(within(screen.getByRole('dialog', { name: 'Navigation' })).getByRole('link', { name: 'Budgets' }))
    expect(document.activeElement?.id).toBe('page-title')
    await user.click(screen.getByRole('button', { name: 'Edit Health budget' }))
    await user.tab({ shift: true }); expect(document.activeElement).toBe(editor().getByRole('button', { name: 'Remove category limit' }))
    await user.tab(); expect(document.activeElement).toBe(editor().getByRole('button', { name: 'Hide amounts in budget editor' }))
    fireEvent(screen.getByRole('dialog', { name: / budget$/ }), new Event('cancel', { cancelable: true }))
    expect(document.activeElement?.id).toBe('budget-edit-health')
  })
  it('shows no budgets instead of a zero plan when every limit is removed, and can undo the last removal', async () => {
    const user = userEvent.setup(); open()
    for (const name of ['Utilities', 'Health', 'Food & groceries', 'Dining', 'Shopping', 'Housing', 'Transport', 'Subscriptions']) {
      await user.click(screen.getByRole('button', { name: `Edit ${name} budget` }))
      await user.click(editor().getByRole('button', { name: 'Remove category limit' }))
    }
    expect(summary().textContent).toContain('No budgets set')
    expect(summary().textContent).not.toContain('₹0')
    expect(document.querySelector('.budget-unbudgeted')?.textContent).toContain('₹35,964.9')
    await user.click(screen.getByRole('button', { name: 'Undo budget change' }))
    expect(summary().textContent).toContain('₹499')
  })
  it.each(['workspace', 'editor', 'expanded'])('has no structural accessibility violations in %s', async mode => {
    const user = userEvent.setup(); const { container } = open()
    if (mode === 'editor') await user.click(screen.getByRole('button', { name: 'Edit Health budget' }))
    if (mode === 'expanded') await user.click(screen.getByRole('button', { name: 'Shopping' }))
    const result = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(result.violations.map(v => v.id)).toEqual([])
  })
})
