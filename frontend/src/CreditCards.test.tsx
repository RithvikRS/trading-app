import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import axe from 'axe-core'
import App from './App'
import { readRoute } from './routes'

function open() { window.history.replaceState(null, '', '/#/credit-cards'); return render(<App />) }
function inspect(id: string) { return screen.getByRole('button', { name: new RegExp(`^Inspect entry ${id}:`) }) }
function entries() { return screen.queryAllByRole('button', { name: /^Inspect entry / }) }

describe('credit-card prototype', () => {
  it('has a dedicated navigable screen, safe routes and independent dated evidence', async () => {
    const user = userEvent.setup(); render(<App />)
    await user.click(screen.getByRole('link', { name: 'Credit Cards' }))
    expect(window.location.hash).toBe('#/credit-cards')
    expect(screen.getByRole('link', { name: 'Credit Cards' }).getAttribute('aria-current')).toBe('page')
    expect(document.activeElement).toBe(screen.getByRole('heading', { level: 1 }))
    expect(readRoute('#/credit-cards/arbitrary')).toEqual({ screen: 'unavailable' })
    expect(screen.getByRole('region', { name: 'Credit account evidence' }).textContent).toContain('₹15,000')
    const current = screen.getByRole('article', { name: 'Separately dated balance evidence' })
    expect(current.textContent).toContain('₹12,400')
    expect(current.textContent).toContain('20 Oct 2026, 10:00 IST')
    expect(within(current).getAllByText('Not supplied')).toHaveLength(2)
    expect(screen.queryByRole('button', { name: /^(pay|upload|connect)\b/i })).toBeNull()
    expect(screen.queryByRole('textbox')).toBeNull()
    expect(entries()).toHaveLength(12)
  })
  it('opens a complete statement with keyboard, shows exact reconciliation, and restores focus', async () => {
    const user = userEvent.setup(); open()
    const opener = screen.getByRole('button', { name: 'October 2026' })
    opener.focus(); await user.keyboard('{Enter}')
    const title = screen.getByRole('heading', { name: 'October 2026 statement' })
    expect(document.activeElement).toBe(title)
    expect(entries()).toHaveLength(7)
    await user.click(screen.getByText('Supplied statement reconciles · Inspect evidence'))
    const detail = screen.getByRole('region', { name: 'October 2026 statement' })
    expect(detail.textContent).toContain('₹750')
    expect(detail.textContent).toContain('₹10,000')
    expect(within(detail).getByText('₹0')).toBeTruthy()
    expect(detail.textContent).toContain('not added together')
    expect(detail.textContent).toContain('Payment status unknown')
    await user.click(screen.getByRole('button', { name: 'Back to statement history' }))
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'October 2026' }))
  })
  it('restores the actual statement opener and falls back safely when filtering removes an inspected row', async () => {
    const user = userEvent.setup(); open()
    await user.click(screen.getByRole('button', { name: 'Inspect latest statement' }))
    await user.click(screen.getByRole('button', { name: 'Back to statement history' }))
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Inspect latest statement' }))
    await user.click(inspect('03'))
    await user.selectOptions(screen.getByLabelText('Card posting status'), 'pending')
    expect(screen.queryByRole('button', { name: /^Inspect entry 03:/ })).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Close source inspection' }))
    expect(document.activeElement).toBe(screen.getByRole('heading', { name: 'Card activity' }))
  })
  it('preserves unknown minimum/opening and missing periods without inferring overdue or paid status', async () => {
    const user = userEvent.setup(); open()
    expect(screen.getByText(/August and earlier statements/).textContent).toContain('do not imply zero')
    await user.click(screen.getByRole('button', { name: 'September 2026' }))
    await user.click(screen.getByText('Reconciliation unavailable · Inspect evidence'))
    const detail = screen.getByRole('region', { name: 'September 2026 statement' })
    expect(within(detail).getAllByText('Not supplied')).toHaveLength(4)
    expect(detail.textContent).toContain('Payment status unknown')
    expect(entries()).toHaveLength(1)
  })
  it('combines filters without changing balance evidence, and clears an empty search safely', async () => {
    const user = userEvent.setup(); open()
    const before = screen.getByRole('region', { name: 'Credit account evidence' }).textContent
    await user.type(screen.getByRole('searchbox'), ' cedar ')
    await user.selectOptions(screen.getByLabelText('Card posting status'), 'posted')
    await user.selectOptions(screen.getByLabelText('Entry type'), 'purchase')
    expect(entries()).toHaveLength(1)
    expect(screen.getByRole('button', { name: /^Inspect entry 03:\s*Cedar home supplies Purchase$/ })).toBe(inspect('03'))
    expect(screen.getByRole('region', { name: 'Credit account evidence' }).textContent).toBe(before)
    await user.clear(screen.getByRole('searchbox'))
    await user.type(screen.getByRole('searchbox'), '<img src=x>')
    expect(screen.getByRole('heading', { name: 'No card entries match.' })).toBeTruthy()
    expect(document.querySelector('img[src=x]')).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Clear filters' }))
    expect(entries()).toHaveLength(12)
  })
  it('distinguishes pending authorizations, payments, refunds and unresolved instalments in inspection', async () => {
    const user = userEvent.setup(); open()
    for (const [id, note] of [['12', 'Excluded from every posted statement'], ['09', 'not a second purchase expense'], ['05', 'not income'], ['11', 'No spending total or future schedule']] as const) {
      await user.click(inspect(id))
      const details = screen.getByRole('region', { name: `Entry ${id} details` })
      expect(details.textContent).toContain(note)
      expect(document.activeElement).toBe(within(details).getByRole('heading'))
      await user.click(within(details).getByRole('button', { name: 'Close source inspection' }))
      expect(document.activeElement).toBe(inspect(id))
    }
    await user.selectOptions(screen.getByLabelText('Card posting status'), 'pending')
    expect(entries()).toHaveLength(1)
    expect(inspect('12')).toBeTruthy()
  })
  it('converts every displayed monetary field while labeling original source amounts', async () => {
    const user = userEvent.setup(); const { container } = open()
    await user.click(inspect('09'))
    for (const currency of ['USD', 'INR']) {
      await user.selectOptions(screen.getByLabelText('Display currency'), currency)
      for (const amount of container.querySelectorAll('.amount')) if (!amount.closest('.original-value')) expect(amount.textContent).toMatch(currency === 'USD' ? /^-?\$/ : /^-?₹/)
    }
    await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    expect(screen.getByRole('article', { name: 'Separately dated balance evidence' }).textContent).toContain('$148.50')
    expect(screen.getByText(/USD is a reporting equivalent/)).toBeTruthy()
    expect(container.querySelector('.original-value')?.textContent).toContain('Original INR')
    await user.click(screen.getByRole('button', { name: 'October 2026' }))
    await user.click(screen.getByText('Supplied statement reconciles · Inspect evidence'))
    expect(screen.getByRole('region', { name: 'October 2026 statement' }).textContent).toContain('$179.64')
  })
  it('masks amounts, limits, narration, descriptions, search text and accessible labels in both themes', async () => {
    const user = userEvent.setup(); const { container } = open()
    await user.type(screen.getByRole('searchbox'), 'Cedar')
    await user.click(inspect('03'))
    await user.click(screen.getByRole('button', { name: 'Hide amounts' }))
    for (const theme of ['dark', 'light']) {
      await user.click(screen.getByRole('button', { name: `Use ${theme} theme` }))
      expect(container.textContent).not.toMatch(/[₹$]|Cedar|3500|100000/)
      expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('')
      expect((screen.getByRole('searchbox') as HTMLInputElement).disabled).toBe(true)
      expect(entries()).toHaveLength(12)
      expect(screen.getByText('Narration hidden')).toBeTruthy()
      for (const element of container.querySelectorAll('[aria-label], [aria-valuetext], [title]')) expect(['aria-label', 'aria-valuetext', 'title'].map(name => element.getAttribute(name)).join(' ')).not.toMatch(/[₹$]|Cedar|3500|100000/)
      expect(container.querySelector('svg[role=img], input[type=range], progress, meter')).toBeNull()
    }
    await user.click(screen.getByRole('button', { name: 'Show amounts' }))
    expect(screen.getByRole('searchbox').getAttribute('value')).toBe('')
    expect(entries()).toHaveLength(12)
  })
  it('keeps incomplete/error evidence distinct and clears details through loading and empty states', async () => {
    const user = userEvent.setup(); open()
    await user.click(inspect('03'))
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(screen.queryByRole('region', { name: 'Entry 03 details' })).toBeNull()
    expect(entries()).toHaveLength(11)
    const current = screen.getByRole('article', { name: 'Separately dated balance evidence' })
    expect(within(current).getAllByText('Not supplied')).toHaveLength(4)
    await user.click(screen.getByRole('button', { name: 'October 2026' }))
    expect(screen.getByText('Reconciliation unavailable · Inspect evidence')).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error')
    expect(screen.getByRole('alert').textContent).toContain('last available sample snapshot')
    await user.click(screen.getByRole('button', { name: 'Retry demo' }))
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading')
    expect(screen.getByRole('status').textContent).toBe('Loading sample credit cards')
    expect(screen.queryByRole('table')).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    expect(screen.getByRole('heading', { name: 'No credit card evidence loaded.' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Explore sample credit cards' }))
    expect(entries()).toHaveLength(12)
    expect(screen.getByRole('region', { name: 'Statement history' })).toBeTruthy()
  })
  it('keeps sample inspection/search state out of URLs and storage and clears it after remount', async () => {
    const user = userEvent.setup(); const first = open()
    await user.type(screen.getByRole('searchbox'), 'Cedar')
    await user.click(inspect('03'))
    expect(window.location.hash).toBe('#/credit-cards')
    expect(Object.keys(localStorage)).toEqual(['portfolio.display.v1'])
    expect(JSON.stringify(localStorage)).not.toContain('Cedar')
    expect(sessionStorage.length).toBe(0)
    first.unmount(); open()
    expect(entries()).toHaveLength(12)
    expect(screen.queryByRole('region', { name: 'Entry 03 details' })).toBeNull()
  })
  it('keeps the existing overview asset value unchanged by liability evidence', async () => {
    const user = userEvent.setup(); open()
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    expect(screen.getByRole('region', { name: 'Asset summary' }).textContent).toContain('₹50,86,080')
  })
  it('passes structural accessibility checks in statement and source inspection views', async () => {
    const user = userEvent.setup(); const { container } = open()
    await user.click(screen.getByRole('button', { name: 'October 2026' }))
    await user.click(inspect('03'))
    const result = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(result.violations.map(item => item.id)).toEqual([])
    fireEvent.change(screen.getByLabelText('Display currency'), { target: { value: 'USD' } })
  })
})
