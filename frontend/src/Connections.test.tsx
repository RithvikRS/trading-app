import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import axe from 'axe-core'
import { describe, expect, it, vi } from 'vitest'
import App from './App'
import { readRoute } from './routes'

function open() { window.history.replaceState(null, '', '/#/connections'); return { ...render(<App />), user: userEvent.setup() } }
const details = (name: string) => within(screen.getByRole('region', { name: `${name} source details` }))
const simulation = () => within(screen.getByRole('region', { name: 'Connector simulation' }))
const expand = (user: ReturnType<typeof userEvent.setup>, name: string) => user.click(screen.getByRole('button', { name: new RegExp(`^${name}`) }))

describe('Connections workspace', () => {
  it('supports the direct route, keeps imports planned, and rejects unknown source/import paths', () => {
    open()
    expect(screen.getByRole('heading', { level: 1 }).textContent).toContain('Know what’s behind the numbers')
    expect(screen.getByRole('link', { name: 'Connections' }).getAttribute('aria-current')).toBe('page')
    expect(screen.getByText('Sample imports').textContent).toContain('Planned')
    expect(screen.queryByRole('button', { name: /Sample imports/ })).toBeNull()
    for (const hash of ['#/connections/imports/i01', '#/connections/hdfc', '#/connections?account=secret', '#/connections/<img>']) expect(readRoute(hash)).toEqual({ screen: 'unavailable' })
  })
  it('explains statement sources without invented authorization, refresh, file selection or credentials', async () => {
    const { user, container } = open()
    for (const name of ['Advisor mutual funds', 'UBS Accenture ESPP', 'HDFC Bank', 'SBI']) {
      await expand(user, name)
      expect(details(name).getByText(/No connector authorization, credentials, or refresh attempt exists/)).toBeTruthy()
      expect(screen.queryByRole('region', { name: 'Connector simulation' })).toBeNull()
      expect(details(name).getByRole('heading', { name: 'Statement walkthrough' })).toBeTruthy()
    }
    expect(details('SBI').getByText('20 Oct 2026, 10:00 IST', { selector: 'dd' })).toBeTruthy()
    expect(container.querySelector('input[type="file"], input[type="password"], form')).toBeNull()
  })
  it('requires renewal for revoked access and keeps attempt, receipt, coverage and permissions distinct', async () => {
    const { user } = open(); await expand(user, 'INDmoney India')
    await user.selectOptions(screen.getByLabelText('Sample scenario'), 'revoked')
    expect((simulation().getByRole('button', { name: 'Retry sample attempt' }) as HTMLButtonElement).disabled).toBe(true)
    expect(simulation().getByText('Revoked in this scenario', { selector: 'dd' })).toBeTruthy()
    await user.click(simulation().getByRole('button', { name: 'Simulate access renewal' }))
    expect(simulation().getByText('Access blocked', { selector: 'dd' })).toBeTruthy()
    expect(document.activeElement).toBe(simulation().getByRole('button', { name: 'Retry sample attempt' }))
    await user.click(simulation().getByRole('button', { name: 'Retry sample attempt' }))
    expect(simulation().getByText('In progress · Simulation', { selector: 'dd' })).toBeTruthy()
    expect(document.activeElement).toBe(simulation().getByRole('button', { name: 'Show sample outcome' }))
    expect((screen.getByLabelText('Sample scenario') as HTMLSelectElement).disabled).toBe(true)
    await user.click(simulation().getByRole('button', { name: 'Show sample outcome' }))
    expect(simulation().getByText('20 Oct 2026, 19:06 IST')).toBeTruthy()
    expect(document.activeElement).toBe(screen.getByLabelText('Sample scenario'))
    expect(details('INDmoney India').getAllByText('20 Oct 2026, 17:30 IST').length).toBeGreaterThan(1)
    expect(details('INDmoney India').getByText(/Actual automatic access and provider permission scopes are unverified/)).toBeTruthy()
  })
  it('walks through rate limiting, never received and stale success without promoting financial freshness', async () => {
    const { user } = open(); await expand(user, 'INDmoney India')
    await user.selectOptions(screen.getByLabelText('Sample scenario'), 'limited')
    expect((simulation().getByRole('button', { name: 'Retry sample attempt' }) as HTMLButtonElement).disabled).toBe(true)
    await user.click(simulation().getByRole('button', { name: 'Simulate retry window' }))
    await user.click(simulation().getByRole('button', { name: 'Retry sample attempt' })); await user.click(simulation().getByRole('button', { name: 'Show sample outcome' }))
    await user.selectOptions(screen.getByLabelText('Sample scenario'), 'never')
    expect(simulation().getByText('Never received', { selector: 'dd' })).toBeTruthy()
    expect(simulation().getByText('Never attempted', { selector: 'dd' })).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Sample scenario'), 'partial')
    await user.click(simulation().getByRole('button', { name: 'Run sample refresh' })); await user.click(simulation().getByRole('button', { name: 'Show sample outcome' }))
    expect(simulation().getByText('Partial sample received', { selector: 'dd' })).toBeTruthy()
    expect(simulation().getByText('17 Oct 2026, 09:00 IST')).toBeTruthy()
    expect(simulation().getByText('Missing stream · No activity received')).toBeTruthy()
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    expect(within(screen.getByRole('region', { name: 'Asset summary' })).getByText('₹50,86,080')).toBeTruthy()
  })
  it('retains compatible scenarios through partial/error, cancels pending work for loading, and clears on empty/reload', async () => {
    const { user, unmount } = open(); await expand(user, 'INDmoney India')
    await user.selectOptions(screen.getByLabelText('Sample scenario'), 'partial')
    await user.click(simulation().getByRole('button', { name: 'Run sample refresh' }))
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading')
    expect(screen.getByRole('status').textContent).toBe('Loading sample sources')
    expect(screen.queryByRole('button', { name: 'Show sample outcome' })).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(simulation().getByText('Sample attempt cancelled', { selector: 'dd' })).toBeTruthy()
    expect(simulation().getByText(/Retry starts another explicit local step/)).toBeTruthy()
    expect(screen.getByRole('region', { name: 'Source summary' }).textContent).toContain('3 sources need attention')
    await user.click(simulation().getByRole('button', { name: 'Run sample refresh' })); await user.click(simulation().getByRole('button', { name: 'Show sample outcome' }))
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error'); await user.click(screen.getByRole('button', { name: 'Retry demo' }))
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    expect(simulation().getByText('Partial sample received', { selector: 'dd' })).toBeTruthy()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error')
    expect(screen.getByRole('alert').textContent).toContain('no accounts')
    await user.click(screen.getByRole('button', { name: 'Explore sample sources' }))
    expect(screen.queryByRole('region', { name: 'Connector simulation' })).toBeNull()
    await expand(user, 'INDmoney India'); expect((screen.getByLabelText('Sample scenario') as HTMLSelectElement).value).toBe('available')
    await user.selectOptions(screen.getByLabelText('Sample scenario'), 'revoked'); unmount(); render(<App />)
    await expand(user, 'INDmoney India'); expect((screen.getByLabelText('Sample scenario') as HTMLSelectElement).value).toBe('available')
  })
  it('preserves source filters and selection through navigation and restores close focus', async () => {
    const { user } = open()
    await user.type(screen.getByRole('searchbox', { name: 'Search sources' }), 'SBI')
    await user.selectOptions(screen.getByLabelText('Source type'), 'bank'); await expand(user, 'SBI')
    await user.click(screen.getByRole('link', { name: 'Budgets' })); await user.click(screen.getByRole('link', { name: 'Connections' }))
    expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('SBI')
    expect(details('SBI').getByText('Financial source coverage')).toBeTruthy()
    await user.click(details('SBI').getByRole('button', { name: 'Close source details' })); expect(document.activeElement?.id).toBe('source-sbi')
    await user.clear(screen.getByRole('searchbox')); await user.type(screen.getByRole('searchbox'), '<img src=x onerror=alert(1)>')
    expect(screen.getByText('No sources match.')).toBeTruthy(); expect(document.querySelector('img')).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Clear source filters' })); expect(screen.getByText('6 of 6 sources')).toBeTruthy()
    act(() => { window.history.replaceState(null, '', '/#/overview'); window.dispatchEvent(new PopStateEvent('popstate')) })
    act(() => { window.history.replaceState(null, '', '/#/connections'); window.dispatchEvent(new PopStateEvent('popstate')) })
    expect(document.activeElement?.id).toBe('page-title')
  })
  it('leaves recurring decisions and budgets intact when connection state resets', async () => {
    const { user } = open()
    await user.click(screen.getByRole('link', { name: 'Budgets' })); await user.click(screen.getByRole('button', { name: 'Recurring' }))
    await user.click(screen.getByRole('button', { name: /^Monthly service fee/ })); await user.click(screen.getByRole('button', { name: 'Confirm recurring' }))
    await user.click(screen.getByRole('link', { name: 'Connections' })); await expand(user, 'INDmoney US')
    await user.click(simulation().getByRole('button', { name: 'Retry sample attempt' })); await user.click(simulation().getByRole('button', { name: 'Show sample outcome' }))
    await user.click(screen.getByRole('button', { name: 'Reset sample connection states' }))
    expect(simulation().getByText('Transient failure', { selector: 'dd' })).toBeTruthy()
    await user.click(screen.getByRole('link', { name: 'Budgets' }))
    expect(screen.getByRole('region', { name: 'Recurring summary' }).textContent).toContain('1 confirmed')
    await user.click(screen.getByRole('button', { name: 'Monthly budgets' }))
    expect(screen.getByRole('region', { name: 'Monthly budget summary' }).textContent).toContain('₹35,959')
    await user.click(screen.getByRole('button', { name: 'Cash flow' }))
    expect(screen.getByRole('region', { name: 'Cash-flow summary' }).textContent).toContain('₹35,964.9')
  })
  it('keeps hidden financial data out of DOM/attributes and persists only display preferences without network calls', async () => {
    const fetchSpy = vi.spyOn(globalThis, 'fetch')
    try {
      const { user, container } = open(); await user.click(screen.getByRole('button', { name: 'Hide amounts' }))
      await user.click(screen.getByRole('button', { name: 'Use dark theme' })); await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
      await expand(user, 'INDmoney India'); await user.selectOptions(screen.getByLabelText('Sample scenario'), 'never')
      await user.click(simulation().getByRole('button', { name: 'Run sample refresh' })); await user.click(simulation().getByRole('button', { name: 'Show sample outcome' }))
      expect(container.innerHTML).not.toMatch(/[₹$]|83\.50|5086080|50,86,080/)
      expect(window.location.hash).toBe('#/connections')
      expect(localStorage.length).toBe(1)
      expect(JSON.parse(localStorage.getItem(localStorage.key(0)!)!)).toEqual({ theme: 'dark', currency: 'USD', hidden: true })
      expect(fetchSpy).not.toHaveBeenCalled()
    } finally { fetchSpy.mockRestore() }
  })
  it('has no detected structural accessibility issues in source and recovery views', async () => {
    const { user, container } = open(); await expand(user, 'INDmoney US')
    await user.selectOptions(screen.getByLabelText('Sample scenario'), 'expired')
    const result = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(result.violations.map(item => `${item.id}: ${item.description}`)).toEqual([])
    fireEvent.click(screen.getByRole('button', { name: 'Open navigation' }))
    expect(within(screen.getByRole('dialog')).getByRole('link', { name: 'Connections' })).toBeTruthy()
  })
})
