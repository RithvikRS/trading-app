import { act, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import axe from 'axe-core'
import { describe, expect, it, vi } from 'vitest'
import App from './App'

function open(id = 'i01') { window.history.replaceState(null, '', `/#/connections/imports/${id}`); return { ...render(<App />), user: userEvent.setup() } }
const button = (name: string | RegExp) => screen.getByRole('button', { name })
const click = (name: string | RegExp) => fireEvent.click(button(name))
function suggestions() { click(/^Review suggested choices/); click('Confirm review change') }
const state = (value: string) => fireEvent.change(screen.getByLabelText('Demo state'), { target: { value } })
const navigate = (hash: string) => act(() => { window.history.replaceState(null, '', `/${hash}`); window.dispatchEvent(new PopStateEvent('popstate')) })

describe('Bank import review interactions', () => {
  it('previews/cancels suggested choices, completes once, reopens, undoes, and resets independently', () => {
    open()
    expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
    click(/^Review suggested choices/)
    expect(screen.getByRole('region', { name: 'Review change preview' }).textContent).toContain('16')
    click('Cancel review change'); expect(screen.queryByText(/Import review history/)).toBeNull()
    suggestions(); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
    click('Complete sample review'); click('Cancel review change')
    expect(screen.queryByText('Sample review completed.')).toBeNull()
    click('Complete sample review'); click('Confirm sample completion')
    expect(screen.getByRole('heading', { name: 'Sample review completed.' })).toBeTruthy()
    expect(screen.getByText('Review receipt · i01 / r1')).toBeTruthy()
    click('Reopen sample review'); click('Confirm review change')
    expect(screen.queryByText(/Review receipt/)).toBeNull()
    click('Undo review change'); expect(screen.getByText('Review receipt · i01 / r1')).toBeTruthy()
    click('Reset sample import reviews'); click('Cancel import reset'); expect(screen.getByText('Review receipt · i01 / r1')).toBeTruthy()
    click('Reset sample import reviews'); click('Confirm import reset')
    expect(screen.queryByText(/Review receipt|Import review history/)).toBeNull()
    expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
  })
  it('resolves the supplied overlap with evidence, reverses a choice, and restores it', async () => {
    const { user } = open('i03'); suggestions()
    fireEvent.change(screen.getByRole('combobox', { name: 'Row disposition' }), { target: { value: 'overlap' } })
    click('Inspect row-t06')
    expect(within(screen.getByRole('dialog')).getByText(/two separate café payments/)).toBeTruthy()
    click('Include candidate'); click('Cancel row choice')
    expect(within(screen.getByRole('dialog')).getByText('Needs decision')).toBeTruthy()
    click('Include candidate'); click('Confirm row choice')
    expect(within(screen.getByRole('dialog')).getByText('Included candidate')).toBeTruthy()
    click('Restore row decision'); click('Confirm row choice')
    expect(within(screen.getByRole('dialog')).getByText('Needs decision')).toBeTruthy()
    click('Include candidate'); click('Confirm row choice')
    await user.click(button('Close import row'))
    expect(screen.getByText('1 of 16 rows shown')).toBeTruthy()
    expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
    click('Undo review change'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
  })
  it('preserves conflict evidence after exclusion and makes set-aside/reopen explicit', () => {
    open('i05'); suggestions(); click('Inspect row-t26')
    expect(within(screen.getByRole('dialog')).queryByRole('button', { name: 'Include candidate' })).toBeNull()
    click('Exclude from this sample review'); click('Confirm row choice')
    expect(within(screen.getByRole('dialog')).getByText(/required evidence and financial blockers remain/i)).toBeTruthy()
    click('Close import row'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
    click('Set sample aside'); click('Confirm review change')
    expect(screen.getByRole('heading', { name: 'This sample is set aside.' })).toBeTruthy()
    click('Reopen sample review'); click('Confirm review change')
    expect(screen.getByText('Import review history · 4 changes')).toBeTruthy()
  })
  it('cancels pending actions on masking and removes amounts from receipts, previews, attributes and storage', () => {
    const fetchSpy = vi.spyOn(globalThis, 'fetch')
    try {
      const { container } = open(); suggestions(); click('Complete sample review'); click('Hide amounts')
      expect(screen.queryByRole('region', { name: 'Review change preview' })).toBeNull()
      expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
      expect(container.innerHTML).not.toMatch(/[₹$]|186420|1,86,420|86,665|95800|95,800/)
      click('Show amounts'); click('Inspect row-t01'); click('Exclude from this sample review'); click('Hide amounts in import inspector')
      expect(screen.queryByRole('region', { name: 'Confirm row decision' })).toBeNull()
      expect((button('Include candidate') as HTMLButtonElement).disabled).toBe(true)
      click('Close import row'); click('Show amounts'); click('Complete sample review'); click('Confirm sample completion')
      click('Hide amounts'); expect(screen.queryByText(/Review receipt/)).toBeNull()
      expect(container.innerHTML).not.toMatch(/[₹$]|186420|1,86,420|86,665|95800|95,800/)
      click('Undo review change'); expect(screen.queryByRole('heading', { name: 'Sample review completed.' })).toBeNull()
      expect(localStorage.length).toBe(1); expect(Object.keys(JSON.parse(localStorage.getItem(localStorage.key(0)!)!)).sort()).toEqual(['currency', 'hidden', 'theme'])
      expect(fetchSpy).not.toHaveBeenCalled(); expect(window.location.hash).toBe('#/connections/imports/i01')
    } finally { fetchSpy.mockRestore() }
  })
  it('uses USD for every primary review/receipt amount and preserves native originals', () => {
    const { container } = open('i03'); suggestions()
    fireEvent.change(screen.getByLabelText('Display currency'), { target: { value: 'USD' } })
    click('Inspect row-t06'); click('Include candidate')
    for (const amount of container.querySelectorAll('.reporting-amount > .amount')) expect(amount.textContent).toContain('$')
    expect(screen.getByRole('region', { name: 'Confirm row decision' }).textContent).toContain('Original INR')
    click('Confirm row choice'); click('Close import row'); click('Complete sample review')
    const preview = screen.getByRole('region', { name: 'Review change preview' })
    expect(preview.textContent).toContain('Original INR')
    for (const amount of preview.querySelectorAll('.reporting-amount > .amount')) expect(amount.textContent).toContain('$')
  })
  it('retains decisions across history/partial/error and drops pending work on loading, empty and reload', () => {
    const { unmount } = open(); suggestions()
    navigate('#/connections/imports/i02'); suggestions(); navigate('#/connections/imports/i01')
    expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
    state('partial'); state('error'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
    click('Complete sample review'); state('loading')
    expect(screen.queryByRole('region', { name: 'Review change preview' })).toBeNull()
    state('populated'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(false)
    expect(screen.queryByRole('region', { name: 'Review change preview' })).toBeNull()
    state('empty'); click('Explore sample imports'); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
    suggestions(); unmount(); render(<App />); expect((button('Complete sample review') as HTMLButtonElement).disabled).toBe(true)
  })
  it('keeps financial totals and connection scenarios independent from import changes/reset', () => {
    open(); suggestions(); click('Complete sample review'); click('Confirm sample completion')
    navigate('#/overview'); expect(within(screen.getByRole('region', { name: 'Asset summary' })).getByText('₹50,86,080')).toBeTruthy()
    navigate('#/connections'); click('Sources'); click('Reset sample connection states')
    navigate('#/connections/imports/i01'); expect(screen.getByText('Review receipt · i01 / r1')).toBeTruthy()
    click('Reset sample import reviews'); click('Confirm import reset')
    navigate('#/overview'); expect(within(screen.getByRole('region', { name: 'Asset summary' })).getByText('₹50,86,080')).toBeTruthy()
  })
  it('has no structural accessibility violations in suggested/completion previews and row choices', async () => {
    const { container } = open('i03'); click(/^Review suggested choices/)
    expect((await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
    click('Confirm review change'); click('Inspect row-t06'); click('Include candidate')
    expect(document.activeElement?.textContent).toBe('Include candidate?')
    expect((await axe.run(screen.getByRole('dialog'), { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
    click('Confirm row choice'); click('Close import row'); click('Complete sample review')
    expect((await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })).violations.map(item => item.id)).toEqual([])
  })
})
