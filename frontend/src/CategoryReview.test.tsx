import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import axe from 'axe-core'
import App from './App'

function open(hash = '#/banking') { window.history.replaceState(null, '', `/${hash}`); return render(<App />) }
function workspace() { return screen.getByRole('region', { name: 'Category review' }) }
function rows() { return within(screen.getByRole('list', { name: 'Category records' })) }
function tab(name: string) { return within(screen.getByRole('group', { name: 'Category review status' })).getByRole('button', { name: new RegExp(`^${name}`) }) }
async function enter(user: ReturnType<typeof userEvent.setup>) { await user.click(screen.getByRole('button', { name: /^Categories/ })) }
async function correct(user: ReturnType<typeof userEvent.setup>, target = 'suggested') {
  const panel = within(screen.getByRole('dialog'))
  await user.selectOptions(panel.getByLabelText('New category'), target)
  await user.click(panel.getByRole('button', { name: 'Preview correction' }))
  await user.click(panel.getByRole('button', { name: 'Apply 1 change' }))
}

describe('category review workspace', () => {
  it('keeps suggestions unapplied, reviews one in inspection, and returns focus when the row leaves the queue', async () => {
    const user = userEvent.setup(); open(); await enter(user)
    expect(tab('Suggestions').textContent).toBe('Suggestions3')
    expect(workspace().textContent).toContain('₹35,964.9')
    await user.click(rows().getByRole('link', { name: /^Unresolved payment/ }))
    const panel = screen.getByRole('dialog')
    expect(panel.textContent).toContain('Recorded categoryUncategorized')
    expect(panel.textContent).toContain('Suggested · Shopping')
    expect(panel.textContent).toContain('Not applied until reviewed')
    expect(within(panel).queryByRole('button', { name: 'Apply 1 change' })).toBeNull()
    await correct(user)
    expect(panel.textContent).toContain('Effective categoryShopping')
    expect(panel.textContent).toContain('Recorded categoryUncategorized')
    expect(panel.textContent).toContain('Supplied sample suggestion explicitly accepted')
    await user.click(within(panel).getByRole('button', { name: 'Close transaction details' }))
    expect(document.activeElement?.id).toBe('category-review-title')
    expect(tab('Reviewed').textContent).toBe('Reviewed1')
    expect(tab('Suggestions').textContent).toBe('Suggestions2')
    expect(workspace().textContent).toContain('₹39,464.9')
  })
  it('corrects and clears a purchase while its refund follows the category, then restores both through undo', async () => {
    const user = userEvent.setup(); open('#/banking/t07')
    await correct(user, 'health')
    expect(screen.getByRole('dialog').textContent).toContain('Recorded categoryShopping')
    expect(screen.getByRole('dialog').textContent).toContain('Effective categoryHealth')
    await correct(user, 'unresolved')
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Close transaction details' }))
    await enter(user)
    expect(workspace().textContent).toContain('₹33,564.9')
    await user.click(rows().getByRole('link', { name: /^Partial purchase refund/ }))
    expect(screen.getByRole('dialog').textContent).toContain('No verified refund is counted')
    expect(within(screen.getByRole('dialog')).queryByLabelText('New category')).toBeNull()
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Undo last change' }))
    expect(screen.getByRole('dialog').textContent).toContain('Refund · Health')
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Undo last change' }))
    expect(screen.getByRole('dialog').textContent).toContain('Refund · Shopping')
  })
  it('previews mixed-direction bulk exclusions and undoes the whole eligible batch', async () => {
    const user = userEvent.setup(); open(); await enter(user); await user.click(tab('All records'))
    for (const checkbox of rows().getAllByRole('checkbox', { name: /^Select Coffee stop/ })) await user.click(checkbox)
    await user.click(rows().getByRole('checkbox', { name: /^Select Account movement received at SBI, 11 Oct/ }))
    await user.selectOptions(screen.getByLabelText('Bulk category'), 'health')
    await user.click(screen.getByRole('button', { name: 'Preview changes' }))
    const preview = screen.getByRole('region', { name: 'Review category changes' })
    expect(preview.textContent).toContain('3 selected · 2 to change · 1 excluded')
    expect(preview.textContent).toContain('Dining'); expect(preview.textContent).toContain('Health')
    expect(preview.textContent).toContain('does not fit this record’s direction')
    expect(document.activeElement?.id).toBe('category-bulk-preview')
    await user.click(within(preview).getByRole('button', { name: 'Apply 2 changes' }))
    expect(tab('Reviewed').textContent).toBe('Reviewed2')
    expect(screen.queryByRole('region', { name: 'Review category changes' })).toBeNull()
    await user.click(screen.getByRole('button', { name: 'Undo last change' }))
    expect(tab('Reviewed').textContent).toBe('Reviewed0')
    expect(tab('Suggestions').textContent).toBe('Suggestions3')
  })
  it('selects only visible eligible records and clears selection and preview on filter/status changes', async () => {
    const user = userEvent.setup(); open(); await enter(user)
    await user.type(screen.getByRole('searchbox', { name: 'Search category records' }), 'Coffee')
    await user.click(screen.getByRole('checkbox', { name: 'Select all eligible visible records' }))
    expect(workspace().textContent).toContain('2 selected · 2 visible')
    await user.click(screen.getByRole('button', { name: 'Preview changes' }))
    expect(screen.getByRole('region', { name: 'Review category changes' }).textContent).toContain('2 to change')
    await user.selectOptions(screen.getByLabelText('Category account'), 'sbi')
    expect(screen.queryByRole('region', { name: 'Review category changes' })).toBeNull()
    expect(workspace().textContent).toContain('0 selected · 0 visible')
    await user.click(screen.getByRole('button', { name: 'Clear category filters' }))
    await user.click(screen.getByRole('checkbox', { name: 'Select all eligible visible records' }))
    expect((rows().getByRole('checkbox', { name: /^Select Incoming payment/ }) as HTMLInputElement).disabled).toBe(true)
    await user.click(tab('Suggestions'))
    expect(workspace().textContent).toContain('0 selected · 3 visible')
    await user.click(screen.getByRole('checkbox', { name: 'Select all eligible visible records' }))
    fireEvent.change(screen.getByLabelText('Category from date'), { target: { value: '2026-10-06' } })
    expect(workspace().textContent).toContain('0 selected · 1 visible')
  })
  it('keeps preview scope independent of search/status/direction and counts a filtered refund in its own period', async () => {
    const user = userEvent.setup(); open(); await enter(user)
    await user.selectOptions(screen.getByLabelText('Category direction'), 'credit')
    expect(screen.getByRole('region', { name: 'Classified spending preview' }).textContent).toContain('₹35,964.9')
    fireEvent.change(screen.getByLabelText('Category from date'), { target: { value: '2026-10-08' } })
    fireEvent.change(screen.getByLabelText('Category to date'), { target: { value: '2026-10-08' } })
    expect(screen.getByRole('region', { name: 'Classified spending preview' }).textContent).toContain('-₹800')
    fireEvent.change(screen.getByLabelText('Category from date'), { target: { value: '2026-10-09' } })
    expect(screen.getByRole('alert').textContent).toContain('Choose valid dates')
    expect(screen.getByRole('region', { name: 'Classified spending preview' }).textContent).toContain('unavailable')
  })
  it('converts and masks coverage, correction previews, inspector values and announcements without persisting financial data', async () => {
    const user = userEvent.setup(); const { container } = open(); await enter(user)
    await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    await user.click(rows().getByRole('checkbox', { name: /^Select Unresolved payment/ }))
    await user.click(screen.getByRole('button', { name: 'Preview changes' }))
    expect(screen.getByRole('region', { name: 'Review category changes' }).textContent).toContain('$41.92')
    expect(screen.getByRole('region', { name: 'Review category changes' }).textContent).toContain('Original INR · ₹3,500')
    await user.click(screen.getByRole('button', { name: 'Hide amounts' }))
    expect(container.textContent).not.toMatch(/[₹$]|3,500|41\.92/)
    await user.click(screen.getByRole('button', { name: 'Apply 1 change' }))
    for (const el of container.querySelectorAll('*')) for (const attr of el.attributes) expect(attr.value).not.toMatch(/[₹$]|3500/)
    for (const status of screen.getAllByRole('status')) expect(status.textContent).not.toMatch(/[₹$]|3500/)
    expect(JSON.stringify(localStorage)).not.toMatch(/t13|shopping|categories|3500/)
    expect(sessionStorage.length).toBe(0)
    await user.click(tab('Reviewed'))
    await user.click(rows().getByRole('link', { name: /^Unresolved payment/ }))
    await correct(user, 'health')
    expect(container.textContent).not.toMatch(/[₹$]|INR 3500/)
  })
  it('retains decisions through navigation and partial/error/retry but clears decisions and selections on reset/empty/reload', async () => {
    const user = userEvent.setup(); const rendered = open(); await enter(user); await user.click(tab('Suggestions'))
    await user.click(screen.getByRole('checkbox', { name: 'Select all eligible visible records' }))
    await user.click(screen.getByRole('button', { name: 'Preview changes' }))
    await user.click(screen.getByRole('button', { name: 'Apply 3 changes' }))
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(tab('Reviewed').textContent).toBe('Reviewed3')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error')
    expect(tab('Reviewed').textContent).toBe('Reviewed3')
    await user.click(screen.getByRole('button', { name: 'Retry demo' }))
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    await user.click(screen.getByRole('link', { name: 'Banking' }))
    expect(tab('Reviewed').textContent).toBe('Reviewed3')
    await user.click(screen.getByRole('button', { name: 'Reset sample decisions' }))
    expect(tab('Reviewed').textContent).toBe('Reviewed0')
    await user.click(screen.getByRole('checkbox', { name: 'Select all eligible visible records' }))
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'populated')
    expect(workspace().textContent).toContain('0 selected')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    await user.click(screen.getByRole('button', { name: 'Explore sample banking' }))
    expect(tab('Reviewed').textContent).toBe('Reviewed0')
    rendered.unmount(); open(); await enter(user)
    expect(tab('Suggestions').textContent).toBe('Suggestions3')
  })
  it('restores the exact originating link and contains keyboard focus across correction controls', async () => {
    const user = userEvent.setup(); open(); await enter(user); await user.click(tab('All records'))
    await user.click(rows().getByRole('link', { name: /^Everyday groceries/ }))
    const panel = within(screen.getByRole('dialog'))
    await user.tab({ shift: true })
    expect(document.activeElement).toBe(panel.getByRole('button', { name: 'Preview correction' }))
    await user.tab()
    expect(document.activeElement).toBe(panel.getByRole('button', { name: 'Hide amounts in inspector' }))
    await correct(user, 'health')
    await user.keyboard('{Escape}')
    fireEvent(screen.getByRole('dialog'), new Event('cancel', { cancelable: true }))
    expect(document.activeElement?.id).toBe('category-link-t14')
    await act(async () => { window.history.back() })
    await waitFor(() => expect(screen.getByRole('dialog').textContent).toContain('Effective categoryHealth'))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Close transaction details' }))
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    expect(screen.getByRole('region', { name: 'Recent activity' }).textContent).toContain('HDFC Bank · Health')
  })
  it.each(['queue', 'bulk preview', 'inspector preview'])('has no structural accessibility violations for %s', async mode => {
    const user = userEvent.setup(); const { container } = open(); await enter(user)
    if (mode === 'bulk preview') { await user.click(screen.getByRole('checkbox', { name: 'Select all eligible visible records' })); await user.click(screen.getByRole('button', { name: 'Preview changes' })) }
    if (mode === 'inspector preview') { await user.click(rows().getByRole('link', { name: /^Unresolved payment/ })); await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Preview correction' })) }
    const results = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(results.violations.map(result => result.id)).toEqual([])
  })
})
