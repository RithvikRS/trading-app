import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import axe from 'axe-core'
import App from './App'
import { getBankTransactions } from './data/banking'
import { formatMoney } from './data/money'
import { readRoute } from './routes'

function renderRoute(hash = '#/banking') { window.history.replaceState(null, '', `/${hash}`); return render(<App />) }
function inspector() { return screen.getByRole('dialog', { name: /./ }) }
function rowLinks() { return screen.getAllByRole('link', { name: /^Inspect / }) }

describe('banking activity and inspection', () => {
  it('shows original transactions and independently dated balance snapshots', () => {
    renderRoute()
    expect(screen.getByRole('heading', { name: 'Everyday money, clearly.' })).toBeTruthy()
    expect(rowLinks()).toHaveLength(28)
    expect(screen.getByRole('region', { name: 'Bank balance snapshots' }).textContent).toContain('₹1,86,420')
    expect(screen.getByRole('region', { name: 'Bank balance snapshots' }).textContent).toContain('₹74,850')
    const summary = screen.getByRole('region', { name: 'Account and date range movements' })
    expect(summary.textContent).toContain('₹1,39,050')
    expect(summary.textContent).toContain('₹93,264.9')
    expect(summary.textContent).toContain('26 posted')
    expect(summary.textContent).toContain('2 pending')
    expect(screen.queryByRole('button', { name: /confirm pair|apply category/i })).toBeNull()
  })
  it('combines filters, preserves fixed balances and scope summaries, and clears active chips', async () => {
    const user = userEvent.setup(); renderRoute()
    await user.click(screen.getByRole('button', { name: 'Filter HDFC Bank activity' }))
    const summary = screen.getByRole('region', { name: 'Account and date range movements' }).textContent
    await user.type(screen.getByRole('searchbox'), ' coffee ')
    await user.click(screen.getByRole('button', { name: 'Filters' }))
    await user.selectOptions(screen.getByLabelText('Recorded category'), 'dining')
    await user.selectOptions(screen.getByLabelText('Review status'), 'recorded')
    await user.selectOptions(screen.getByLabelText('Direction'), 'debit')
    expect(rowLinks()).toHaveLength(2)
    expect(screen.getByRole('region', { name: 'Account and date range movements' }).textContent).toBe(summary)
    expect(screen.getByRole('region', { name: 'Bank balance snapshots' }).textContent).toContain('₹1,86,420')
    expect(screen.getByRole('status').textContent).not.toMatch(/[₹$]/)
    await user.click(screen.getByRole('button', { name: 'Clear all' }))
    expect(rowLinks()).toHaveLength(28)
    await user.selectOptions(screen.getByLabelText('Posting status'), 'pending')
    expect(rowLinks()).toHaveLength(2)
    expect(screen.getByRole('region', { name: 'Account and date range movements' }).textContent).toContain('₹1,39,050')
  })
  it('validates date ranges and distinguishes an empty search from an empty portfolio', async () => {
    const user = userEvent.setup(); renderRoute()
    fireEvent.change(screen.getByLabelText('From booking date'), { target: { value: '2026-10-21' } })
    expect(screen.getByRole('alert').textContent).toContain('start on or before')
    expect(screen.getByRole('region', { name: 'Account and date range movements' }).textContent).toContain('unavailable')
    await user.click(screen.getByRole('button', { name: 'Clear all filters' }))
    await user.type(screen.getByRole('searchbox'), '<img src=x>')
    expect(screen.getByRole('heading', { name: 'No transactions match these filters.' })).toBeTruthy()
    expect(document.querySelector('img[src="x"]')).toBeNull()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'empty')
    expect(screen.getByRole('heading', { name: 'No bank activity loaded.' })).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Explore sample banking' }))
    expect(rowLinks()).toHaveLength(28)
  })
  it('opens every known transaction directly with its own source and original amount', () => {
    for (const item of getBankTransactions()) {
      const view = renderRoute(`#/banking/${item.id}`)
      const panel = inspector()
      expect(within(panel).getByRole('heading', { level: 2 }).textContent).toBe(item.description)
      expect(panel.textContent).toContain(formatMoney(item.amount))
      expect(panel.textContent).toContain(item.narration)
      expect(panel.textContent).toContain(item.sourceId)
      expect(document.activeElement?.id).toBe('transaction-title')
      view.unmount()
    }
    expect(document.body.style.overflow).toBe('')
  })
  it('restores filters, sort, scroll and row focus, including browser Back/Forward', async () => {
    const user = userEvent.setup(); renderRoute()
    await user.type(screen.getByRole('searchbox'), 'Coffee')
    await user.click(screen.getByRole('button', { name: 'Filters' }))
    await user.selectOptions(screen.getByLabelText('Sort activity'), 'amount:asc')
    Object.defineProperty(window, 'scrollY', { configurable: true, value: 720 })
    await user.click(rowLinks()[1]!)
    expect(window.location.hash).toBe('#/banking/t06')
    expect(document.activeElement?.id).toBe('transaction-title')
    await user.click(screen.getByRole('button', { name: 'Close transaction details' }))
    expect(document.activeElement?.id).toBe('transaction-link-t06')
    expect((screen.getByRole('searchbox') as HTMLInputElement).value).toBe('Coffee')
    expect((screen.getByLabelText('Sort activity') as HTMLSelectElement).value).toBe('amount:asc')
    expect(screen.getByRole('button', { name: 'Filters' }).getAttribute('aria-expanded')).toBe('true')
    await waitFor(() => expect(window.scrollTo).toHaveBeenLastCalledWith({ top: 720, behavior: 'instant' }))
    await act(async () => { window.history.back() })
    await waitFor(() => expect(screen.getByRole('dialog', { name: 'Coffee stop' })).toBeTruthy())
    await act(async () => { window.history.forward() })
    await waitFor(() => expect(document.activeElement?.id).toBe('transaction-link-t06'))
    expect(JSON.stringify(localStorage)).not.toContain('Coffee')
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    await user.click(screen.getByRole('link', { name: 'Banking' }))
    expect(rowLinks()).toHaveLength(2)
  })
  it('contains inspector keyboard focus and restores the list heading for direct entry', async () => {
    const user = userEvent.setup(); renderRoute('#/banking/t08')
    await user.tab({ shift: true })
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Close transaction details' }))
    await user.tab()
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Hide amounts in inspector' }))
    fireEvent(inspector(), new Event('cancel', { cancelable: true }))
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(document.activeElement?.id).toBe('page-title')
  })
  it('keeps INR source values through reporting-currency changes and distinguishes pending records', async () => {
    const user = userEvent.setup(); renderRoute()
    await user.selectOptions(screen.getByLabelText('Display currency'), 'USD')
    await user.click(screen.getByRole('link', { name: /^Inspect Online purchase / }))
    const panel = inspector()
    expect(panel.textContent).toContain('₹1,299')
    expect(panel.textContent).toContain('$15.56')
    expect(panel.textContent).toContain('Pending record. Excluded')
    expect(panel.textContent).toContain('Reporting equivalent only')
    expect(panel.textContent).toContain('Value dateNot supplied')
  })
  it('masks source narration and every amount even in the background DOM and accessible attributes', async () => {
    const user = userEvent.setup(); const { container } = renderRoute('#/banking/t08')
    await user.click(screen.getByRole('button', { name: 'Hide amounts in inspector' }))
    expect(container.textContent).not.toMatch(/[₹$]|INR 800/)
    expect(container.querySelector('.amount')).toBeNull()
    expect(inspector().textContent).toContain('Reference hidden')
    expect(inspector().textContent).toContain('Narration hidden')
    for (const element of container.querySelectorAll('[title], [aria-label], [aria-valuetext]')) expect(['title', 'aria-label', 'aria-valuetext'].map(name => element.getAttribute(name)).join(' ')).not.toMatch(/[₹$]|INR 800/)
    await user.click(screen.getByRole('button', { name: 'Close transaction details' }))
    await user.click(screen.getByRole('link', { name: 'Overview' }))
    expect(container.querySelector('.amount')).toBeNull()
  })
  it('retains partial source coverage and balance on error, then recovers without duplicating rows', async () => {
    const user = userEvent.setup(); renderRoute()
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    expect(rowLinks()).toHaveLength(27)
    expect(screen.getByRole('region', { name: 'Bank balance snapshots' }).textContent).toContain('-₹2,200')
    expect(screen.getByRole('region', { name: 'Bank balance snapshots' }).textContent).toContain('₹74,850')
    await user.selectOptions(screen.getByLabelText('Demo state'), 'error')
    expect(screen.getByRole('alert').textContent).toContain('last available')
    await user.click(screen.getByRole('button', { name: 'Retry demo' }))
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    expect(rowLinks()).toHaveLength(27)
    await user.selectOptions(screen.getByLabelText('Demo state'), 'loading')
    expect(screen.getByRole('status').textContent).toBe('Loading sample bank activity')
    expect(screen.queryByRole('table')).toBeNull()
  })
  it('handles known records absent in partial data and invalid routes safely', async () => {
    const user = userEvent.setup(); renderRoute('#/banking/t26')
    // The demo control is outside a native modal; close it before changing the fixture.
    await user.click(screen.getByRole('button', { name: 'Close transaction details' }))
    await user.selectOptions(screen.getByLabelText('Demo state'), 'partial')
    await act(async () => { window.history.back() })
    await waitFor(() => expect(screen.getByRole('dialog', { name: 'Transaction unavailable' })).toBeTruthy())
    for (const hash of ['#/banking/t99', '#/banking/%74%30%31', '#/banking/<img>', '#/banking/t01?amount=1', '#/banking/t01/extra']) expect(readRoute(hash)).toEqual({ screen: 'unavailable' })
  })
  it.each(['#/banking', '#/banking/t08'])('has no detectable structural accessibility violations for %s', async hash => {
    const { container } = renderRoute(hash)
    const result = await axe.run(container, { rules: { 'color-contrast': { enabled: false } } })
    expect(result.violations.map(item => `${item.id}: ${item.description}`)).toEqual([])
  })
})
